#!/usr/bin/env python3
"""
ports.py -- CosmoOS's CeeSafe ports through a ceesafec: the CeeSafe side of `c2cee.py verify` (spec/tooling.md §9).

CosmoOS writes its kernel ports in CeeSafe (since its move from Nova, 2026-10-31), and its build generates their C
with the ceesafec it pins (its scripts/cee-gen.py; build/cee.mk); the generated C is not committed. This check runs
CosmoOS's own cee-gen.py, at a commit, with the ceesafec under test ($CEESAFEC, else the tree's out/ceesafec):

- every port compiles, with cee-gen.py's own flags, port list and banners (its `generated`);
- the sources the kernel must refuse (tests/ceesafe/negative/*.cee) give exactly their annotated errors (its
  `refused`);
- with --pinned <ceesafec>, the files it generates equal, byte for byte apart from the compiler's banner line, what
  that ceesafec generates: run with the release CosmoOS pins, it is the regression check before a CeeSafe release
  CosmoOS would move to. A difference is a defect, or an intended change that CosmoOS takes by bumping its pin and
  reviewing the difference (its docs/build/ceesafe.md, "Upgrading the compiler").

The tree is read from a commit (`git archive`) into a scratch directory; nothing in the CosmoOS checkout is changed.

usage: python3 integrations/cosmoos/ports.py [--cosmoos ~/dev/CosmoOS] [--commit origin/main] [--pinned <ceesafec>]
"""

import argparse
import difflib
import importlib.util
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CEESAFEC = Path(os.environ.get("CEESAFEC", ROOT / "out" / "ceesafec")).resolve()
# The one difference allowed between two compilers' output: the banner naming the compiler's version (c-backend.md §1).
# The C and the exports headers both carry it: "/* Generated by ceesafec <version>. Do not edit. ..." on their first line.
BANNER = re.compile(r"^/\* Generated by ceesafec \S+\. Do not edit\.", re.M)


def version(exe: Path) -> str:
    return subprocess.run([exe, "--version"], capture_output=True, text=True).stdout.strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--cosmoos", default=str(Path.home() / "dev" / "CosmoOS"))
    parser.add_argument("--commit", default="origin/main")
    parser.add_argument("--pinned", help="a ceesafec to compare the generated files with (the release CosmoOS pins)")
    args = parser.parse_args()
    if not CEESAFEC.is_file():
        sys.exit(f"ports: {CEESAFEC} is missing: build ceesafec or set CEESAFEC")
    pinned = Path(args.pinned).expanduser().resolve() if args.pinned else None
    if pinned is not None and not pinned.is_file():
        sys.exit(f"ports: --pinned {pinned} is missing")
    cosmoos = Path(args.cosmoos).expanduser().resolve()
    commit = subprocess.run(["git", "-C", cosmoos, "rev-parse", "--short", args.commit], capture_output=True, text=True,
                            check=True).stdout.strip()
    problems = []
    with tempfile.TemporaryDirectory(prefix="cosmoos-ports-") as work:
        tree = Path(work) / "tree"
        tree.mkdir()
        archive = subprocess.run(["git", "-C", cosmoos, "archive", commit], capture_output=True, check=True).stdout
        subprocess.run(["tar", "-x", "-C", tree], input=archive, check=True)
        script = tree / "scripts" / "cee-gen.py"
        if not script.is_file():
            sys.exit(f"ports: CosmoOS {commit} has no scripts/cee-gen.py: it predates its move to CeeSafe (it built "
                     "with novac)")
        spec = importlib.util.spec_from_file_location("cee_gen", script)
        gen = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(gen)   # its ROOT is the scratch tree, so its compiler runs there

        def generate(exe: Path, name: str):
            try:
                return gen.generated(str(exe), Path(work) / name)
            except subprocess.CalledProcessError as e:
                problems.append(f"{exe}: a port failed to compile: {' '.join(map(str, e.cmd))[-160:]}")
                return None

        ours = generate(CEESAFEC, "under-test")
        for line in gen.refused(str(CEESAFEC)):
            problems.append(line)
        compared = 0
        if pinned is not None and ours is not None:
            theirs = generate(pinned, "pinned")
            if theirs is not None:
                for path in sorted(set(ours) | set(theirs)):
                    if path not in ours or path not in theirs:
                        problems.append(f"{path}: generated by only {'the pinned' if path in theirs else 'the tested'} ceesafec")
                        continue
                    compared += 1
                    a, b = BANNER.sub("/* Generated by ceesafec. Do not edit.", theirs[path]), BANNER.sub("/* Generated by ceesafec. Do not edit.", ours[path])
                    if a != b:
                        changed = sum(1 for l in difflib.unified_diff(a.splitlines(), b.splitlines(), n=0)
                                      if l[:1] in "+-" and not l.startswith(("+++", "---")))
                        problems.append(f"{path}: {changed} lines differ from the pinned ceesafec's")
    for p in problems:
        print("FAIL", p)
    ports = len(gen.PORTS)
    against = f", {compared} generated files equal to {version(pinned)}'s" if pinned else ""
    print(f"ports: CosmoOS {commit} (pins ceesafec {gen.CEESAFEC_VERSION}) with {version(CEESAFEC)}: {ports} ports, "
          f"{len(gen.NEGATIVE)} negative sources{against}: {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
