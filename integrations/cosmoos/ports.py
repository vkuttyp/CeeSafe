#!/usr/bin/env python3
"""
ports.py -- CosmoOS's Nova ports through ceesafec: the CeeSafe side of `c2cee.py verify` (spec/tooling.md §9).

CosmoOS keeps its kernel ports as Nova and checks in the C its pinned novac generates from them (scripts/nova-gen.py,
`make nova`). At the fork the two languages are the same, and novac 0.6.0's output is CeeSafe's baseline
(docs/fork-point.md), so ceesafec, given each port as a `.cee` copy with nova-gen.py's own flags, must generate that
C byte for byte once CeeSafe's names are mapped back (tools/names.py), the banner's version aside: each port's C, its exports header and the
runtime. The sources the kernel must refuse (tests/nova/negative/*.nova) must give exactly their annotated errors.

The tree is read from a commit (`git archive`) into a scratch directory; nothing in it is changed. Its pin must be
novac 0.6.0, the release CeeSafe forked from: after a bump the check stops, since the baseline is then another
compiler's.

usage: python3 integrations/cosmoos/ports.py [--cosmoos ~/dev/CosmoOS] [--commit origin/main]
"""

import argparse
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from names import map_back  # noqa: E402

CEESAFEC = Path(os.environ.get("CEESAFEC", ROOT / "out" / "ceesafec")).resolve()
FORK = "0.6.0"
# The one difference allowed: the generated-C banner names the compiler's version (tools/run_corpus.py's only
# normalisation of C, c-backend.md §1).
BANNER = re.compile(r"^/\* Generated by novac \S+\. Do not edit\.", re.M)


def baseline(text):
    """ceesafec's output as novac 0.6.0 would write it: CeeSafe's names mapped back, the banner's version 0.6.0."""
    return BANNER.sub(f"/* Generated by novac {FORK}. Do not edit.", map_back(text), count=1)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--cosmoos", default=str(Path.home() / "dev" / "CosmoOS"))
    parser.add_argument("--commit", default="origin/main")
    args = parser.parse_args()
    if not CEESAFEC.is_file():
        sys.exit(f"ports: {CEESAFEC} is missing: build ceesafec or set CEESAFEC")
    cosmoos = Path(args.cosmoos).expanduser().resolve()
    commit = subprocess.run(["git", "-C", cosmoos, "rev-parse", "--short", args.commit], capture_output=True, text=True,
                            check=True).stdout.strip()
    problems, compared = [], 0
    with tempfile.TemporaryDirectory(prefix="cosmoos-ports-") as work:
        tree = Path(work) / "tree"
        tree.mkdir()
        archive = subprocess.run(["git", "-C", cosmoos, "archive", commit], capture_output=True, check=True).stdout
        subprocess.run(["tar", "-x", "-C", tree], input=archive, check=True)
        spec = importlib.util.spec_from_file_location("nova_gen", tree / "scripts" / "nova-gen.py")
        gen = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(gen)
        if gen.NOVAC_VERSION != FORK:
            sys.exit(f"ports: CosmoOS {commit} pins novac {gen.NOVAC_VERSION}, not {FORK}, the release CeeSafe forked "
                     "from; its generated C is not CeeSafe's baseline")
        runtime = {}
        for i, (source, target, title, header, kernel) in enumerate(gen.PORTS):
            copy = source[:-len(".nova")] + ".cee"
            shutil.copy(tree / source, tree / copy)
            out = Path(work) / str(i)
            include = None if header is None else str(Path(header).relative_to("kernel/include"))
            built = subprocess.run([CEESAFEC, "build", "--profile", "freestanding", "--no-float",
                                    *(["--kernel", "cosmoos"] if kernel else []),
                                    *(["--exports-header", include] if include else []), "--emit", "c", "-o", out, copy],
                                   cwd=tree, capture_output=True, text=True)
            if built.returncode != 0:
                problems.append(f"{source}: ceesafec failed: {(built.stdout + built.stderr).strip()[:300]}")
                continue
            banner = gen.BANNER.format(name=Path(target).name, title=title, source=source)
            pairs = [(target, banner + baseline((out / "main.c").read_text()))]
            if include is not None:
                pairs.append((header, gen.BANNER.format(name=Path(header).name, title=title + ": its C interface",
                                                        source=source) + baseline((out / include).read_text())))
            for made, path in (("ceesafe/rt.h", "kernel/include/nova/rt.h"), ("ceesafe_rt_core.c", "kernel/nova/nova_rt_core.c")):
                runtime.setdefault(path, baseline((out / made).read_text()))
            for path, text in pairs:
                compared += 1
                if (tree / path).read_text() != text:
                    problems.append(f"{path}: differs from ceesafec's output for {source}, mapped back")
        for path, text in runtime.items():
            compared += 1
            if (tree / path).read_text() != text:
                problems.append(f"{path}: differs from ceesafec's runtime, mapped back")
        negative = 0
        for source in gen.NEGATIVE:
            copy = source[:-len(".nova")] + ".cee"
            shutil.copy(tree / source, tree / copy)
            expected = set()
            for number, line in enumerate((tree / source).read_text().splitlines(), 1):
                expected.update((number, code) for code in re.findall(r"//\s*error\[(N\d{4})\]", line))
            run = subprocess.run([CEESAFEC, "check", "--profile", "freestanding", "--no-float", "--kernel", "cosmoos",
                                  "--diagnostics-format=json", copy], cwd=tree, capture_output=True, text=True)
            found = {(d["start"]["line"], d["code"]) for d in json.loads(run.stdout)["diagnostics"]}
            negative += 1
            if found != expected:
                problems.append(f"{source}: errors {sorted(found)}, annotated {sorted(expected)}")
    for p in problems:
        print("FAIL", p)
    print(f"ports: CosmoOS {commit} (novac {FORK} pinned): {len(gen.PORTS)} ports, {compared} generated files compared "
          f"with ceesafec's output mapped back, {negative} negative sources: {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
