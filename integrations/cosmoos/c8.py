#!/usr/bin/env python3
"""
c8.py -- CeeSafe milestone C8: an experimental kernel module written in CeeSafe (docs/cosmoos/c8-report.md). CosmoOS is only
read.

The module is c8/module.cee: its state is one CeeSafe value that init makes and shutdown drops, owning a timer, a kernel
thread and a shared kernel object (bindings c8/timer.cee, c8/kthread.cee, and C7's). Its COSMO_MODULE glue is
generated here (generate_glue): metadata, init and shutdown wrappers that keep the CeeSafe state's pointer.

Steps:
  1. negative cases: each c8/negative/*.cee, compiled with the bindings, gives exactly its annotated diagnostics;
  2. host test (c8/host_test.c) with CosmoOS's HOST_CFLAGS, its harness, spinlock shim and kernel/object/object.c:
     the lifecycle and its teardown order, and an allocation-failure sweep over init;
  3. C8a in the kernel: the module built with CosmoOS's debug MODULE_CFLAGS, signed, checked (check-module-elf.py and
     C4's checks), loaded at boot from modules/ceesafe_c8.ko in QEMU (4 CPUs, lockdep on): init runs, the timer fires
     and the thread sees it, no lockdep report, no module failing, CosmoOS's selftests pass, clean shutdown;
  4. C8b (--cycles N): CosmoOS's debug build loads and unloads the module N times at boot through its module-cycle
     hook (module.cycle=tests/ceesafe_c8.ko:N; CosmoOS #457, merged 2026-10-26 from proposals/module-cycle/); then once
     more with a module whose shutdown leaks a kernel-object reference, which must make it a zombie. CosmoOS itself
     is built, into CeeSafe's out/ directory; before the hook was merged this step patched a copy of the tree.

Usage:
    python3 integrations/cosmoos/c8.py --arch aarch64|x86_64 [--cosmoos ~/dev/CosmoOS] [--no-boot] [--cycles 1000]
"""

import argparse
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import c1  # noqa: E402
import c4  # noqa: E402

COSMOOS_DIR = Path(__file__).resolve().parent
C8_DIR = COSMOOS_DIR / "c8"
BINDINGS = ["integrations/cosmoos/c5/kernel.cee", "integrations/cosmoos/c7/sync.cee", "integrations/cosmoos/c7/kobject.cee",
            "integrations/cosmoos/c7/quiesce.cee", "integrations/cosmoos/c8/kthread.cee", "integrations/cosmoos/c8/timer.cee"]
PACKAGE = [*BINDINGS, "integrations/cosmoos/c8/module.cee"]
MODULE = "ceesafe_c8"
ANNOTATION = re.compile(r"// error\[(N\d{4})\]")
# A diagnostic reported in another file (a generic callback's instance): its code and a part of its message.
ELSEWHERE = re.compile(r"^// expect-error: (N\d{4}) (.+)$", re.MULTILINE)
DIAGNOSTIC = re.compile(r"^(?P<file>[^:\n]+):(?P<line>\d+):\d+: error\[(?P<code>N\d{4})\]", re.MULTILINE)

GLUE = """/*
 * Generated by integrations/cosmoos/c8.py: the COSMO_MODULE glue of a CeeSafe module (docs/cosmoos/c8-report.md).
 * Do not edit. The module's state is one CeeSafe value: novamod_init makes it and hands over its address, which this
 * file keeps until novamod_shutdown takes it back and drops it.
 */
#include <kernel/errno.h>
#include <kernel/log.h>
#include <kernel/module.h>

#include "ceesafe_exports.h"

void c8_log(const char *event, uint64_t value);
bool c8_leak_requested(void);

static void *g_state;

void c8_log(const char *event, uint64_t value)
{
    if (!@QUIET@)
        kinfo("@NAME@: %s (%llu)", event, (unsigned long long)value);
}

bool c8_leak_requested(void)
{
    return @LEAK@;
}

static int ceesafe_module_init(void)
{
    void *state = NULL;
    int32_t rc = novamod_init(&state);
    if (rc == 0)
        g_state = state;
    return rc;
}

static void ceesafe_module_shutdown(void)
{
    void *state = g_state;
    g_state = NULL;
    if (state != NULL)
        novamod_shutdown(state);
}

COSMO_MODULE("@NAME@", "@VERSION@", ceesafe_module_init, ceesafe_module_shutdown, "", MODULE_CAP_NONE);
"""


def run(cmd, **kwargs):
    return subprocess.run([str(c) for c in cmd], capture_output=True, text=True, **kwargs)


def generate_glue(path, name, version, leak=False, quiet=False):
    path.write_text(GLUE.replace("@NAME@", name).replace("@VERSION@", version)
                    .replace("@LEAK@", "true" if leak else "false").replace("@QUIET@", "1" if quiet else "0"))


def negative_cases(checks):
    for case in sorted((C8_DIR / "negative").glob("*.cee")):
        relative = case.relative_to(c1.CEESAFE_ROOT)
        expected = {(n, m.group(1)) for n, text in enumerate(case.read_text().splitlines(), 1) for m in ANNOTATION.finditer(text)}
        result = run([c1.CEESAFEC, "check", "--profile", "freestanding", "--no-float", *BINDINGS, relative], cwd=c1.CEESAFE_ROOT)
        output = result.stdout + result.stderr
        found = {(int(m.group("line")), m.group("code")) for m in DIAGNOSTIC.finditer(output) if m.group("file") == str(relative)}
        elsewhere = ELSEWHERE.findall(case.read_text())
        lines = [l for l in output.splitlines() if DIAGNOSTIC.match(l) and not l.startswith(str(relative))]
        unmatched = [l for l in lines if not any(f"error[{code}]" in l and text in l for code, text in elsewhere)]
        missing = [f"{code} {text}" for code, text in elsewhere if not any(f"error[{code}]" in l and text in l for l in lines)]
        ok = found == expected and not unmatched and not missing and result.returncode != 0
        codes = [code for _, code in sorted(expected)] + [code for code, _ in elsewhere]
        checks[f"negative {case.name}: {', '.join(codes)}"] = (ok, [] if ok else [f"expected {sorted(expected)}, found {sorted(found)}", *missing, *unmatched[:4]])


def host_test(cosmo, root, gen, work, checks):
    cc = cosmo.var("HOST_CC")
    cflags, ldflags = shlex.split(cosmo.var("HOST_CFLAGS")), shlex.split(cosmo.var("HOST_LDFLAGS"))
    sources = [gen / "main.c", gen / "ceesafe_rt_core.c", c4.C4_DIR / "ceesafe_rt_kernel.c", COSMOOS_DIR / "c7" / "host_kernel.c",
               C8_DIR / "host_shims.c", C8_DIR / "host_test.c", root / "kernel" / "object" / "object.c",
               *[root / s for s in shlex.split(cosmo.var("HOST_COMMON_SRCS"))]]
    exe = work / "host_test"
    built = run([cc, *cflags, "-I", gen, "-ffreestanding", "-fno-stack-protector", "-I", root / "tests" / "host", *sources, *ldflags, "-o", exe])
    if built.returncode != 0:
        checks["host test builds with CosmoOS's HOST_CFLAGS"] = (False, built.stderr.strip().splitlines()[:10])
        return
    ran = run([exe], timeout=600, env={"ASAN_OPTIONS": f"detect_leaks={0 if sys.platform == 'darwin' else 1}", "PATH": "/usr/bin:/bin"})
    lines = (ran.stdout + ran.stderr).strip().splitlines()
    checks[f"host test c8/host_test.c: {lines[-1] if lines else 'no output'}"] = (ran.returncode == 0, lines[-10:] if ran.returncode else [])


def build_module(cosmo, gen, work, leak=False, quiet=False):
    """ceesafe_c8.ko for `cosmo`'s build, as build/module.mk builds a module."""
    work.mkdir(parents=True, exist_ok=True)
    glue = work / "glue.c"
    generate_glue(glue, MODULE, "1.0", leak=leak, quiet=quiet)
    cflags, ldflags = shlex.split(cosmo.var("MODULE_CFLAGS")), shlex.split(cosmo.var("MODULE_LDFLAGS"))
    objects, usage, errors = [], [], []
    for source in [gen / "main.c", gen / "ceesafe_rt_core.c", c4.C4_DIR / "ceesafe_rt_kernel.c", glue]:
        obj = work / f"{source.stem}.o"
        compiled = c4.compile_c(cosmo.var("CC"), cflags, source, obj, gen, ["-fstack-usage"])
        if compiled.returncode != 0:
            errors.append(compiled.stderr.strip())
        objects.append(obj)
        usage.append(obj.with_suffix(".su"))
    if errors:
        return None, [line for e in errors for line in e.splitlines()][:10]
    unsigned, module = work / f"{MODULE}.ko.unsigned", work / f"{MODULE}.ko"
    c1.run([cosmo.var("LD"), *ldflags, "-o", unsigned, *objects])
    c1.run([sys.executable, cosmo.root / "scripts" / "modsign.py", "sign", "--key", cosmo.var("MODSIGN_KEY"), "--in", unsigned, "--out", module])
    elf_check = run([sys.executable, cosmo.root / "scripts" / "check-module-elf.py", module, cosmo.arch])
    problems, _, _ = c4.all_problems(unsigned, cosmo.arch, c4.kernel_exports(), cosmo.var("OBJDUMP"))
    problems = [p for p in problems if "mutable global state" not in p]  # the glue keeps the state's pointer
    frames, _ = c4.frame_problems(usage, int(cosmo.var("KERNEL_FRAME_LIMIT")))
    return module, problems + frames + ([] if elf_check.returncode == 0 else elf_check.stderr.splitlines())


def boot_lines(cosmo, work, extra, timeout, cmdline=None):
    image = c1.make_image(cosmo, work, [], extra=extra, cmdline_extra=cmdline)
    try:
        serial, status = c1.boot(cosmo, work, image, [], timeout)
    except SystemExit:
        serial, status = (work / "serial.log").read_bytes().decode("utf-8", "replace"), None
    return [line.strip() for line in serial.replace("\r", "\n").split("\n")], status


def common_boot_checks(arch, lines, status, checks, label):
    reports = [l for l in lines if l.startswith("lockdep:") or "panic" in l.lower()]
    checks[f"{arch} {label}: no lockdep report, no panic"] = (not reports, reports[:6])
    loaded = next((l for l in lines if re.search(r"module: \d+ boot module\(s\) loaded", l)), "")
    checks[f"{arch} {label}: boot modules: {loaded.split('module: ')[-1] if loaded else 'no line'}"] = (loaded.endswith(", 0 failed"), [])
    selftests = next((l for l in lines if l.startswith("SELFTEST: PASS") or l.startswith("SELFTEST: FAIL")), "no SELFTEST summary")
    checks[f"{arch} {label}: CosmoOS selftests: {selftests}"] = (selftests.startswith("SELFTEST: PASS"), [])
    checks[f"{arch} {label}: CosmoOS shut down cleanly (QEMU exit status {status})"] = (status == 33, [])


def boot_at_load(root, arch, gen_debug, timeout, checks):
    """C8a: the module loaded at boot from modules/ceesafe_c8.ko, in CosmoOS's debug build."""
    cosmo = c1.Cosmo(root, arch, c1.CEESAFE_ROOT / "out" / "cosmoos" / f"{arch}-debug", build="debug")
    cosmo.make("image")
    work = c1.CEESAFE_ROOT / "out" / "cosmoos" / f"c8-boot-{arch}"
    module, problems = build_module(cosmo, gen_debug, work)
    checks[f"{arch} debug build: {MODULE} built, signed, checked (check-module-elf.py, C4's checks)"] = (module is not None and not problems, problems)
    if module is None:
        return
    lines, status = boot_lines(cosmo, work, [(f"modules/{MODULE}.ko", module)], timeout)
    started = any(f"{MODULE}: init: timer and thread started" in l for l in lines)
    checks[f"{arch} C8a: init ran (timer armed, thread started)"] = (started, [])
    seen = next((re.search(r"ticks seen after 100 steps \((\d+)\)", l) for l in lines if "ticks seen after 100 steps" in l), None)
    ticks = int(seen.group(1)) if seen else 0
    checks[f"{arch} C8a: the thread saw the timer fire ({ticks} ticks after 100 steps)"] = (ticks > 0, [])
    common_boot_checks(arch, lines, status, checks, "C8a")


def boot_cycles(root, arch, gen_debug, cycles, timeout, checks):
    """C8b: CosmoOS itself, loading and unloading the module `cycles` times through its module-cycle hook."""
    if not (root / "kernel" / "module" / "modcycle.c").exists():
        checks[f"{arch} C8b: CosmoOS has the module-cycle hook (kernel/module/modcycle.c, #457)"] = (False, [])
        return
    work = c1.CEESAFE_ROOT / "out" / "cosmoos" / f"c8-cycles-{arch}"
    # Objects built from another tree (a patched copy, before the hook was merged) can be newer than this tree's
    # sources, so make keeps them and links a kernel of two trees (2026-10-28: it panicked at boot). The output
    # directory records the tree it was built from and is started afresh for any other.
    stamp = work / "source-tree"
    if work.exists() and (not stamp.exists() or stamp.read_text() != str(root)):
        shutil.rmtree(work)
    work.mkdir(parents=True, exist_ok=True)
    stamp.write_text(str(root))
    cosmo = c1.Cosmo(root, arch, work / "out", build="debug")
    cosmo.make("image")
    # The control holds each load 100 ms, so its thread makes the leaked object while the module is live: objects
    # made while init or shutdown runs are attributed to no module (c8-report.md, findings).
    for label, leak, count, hold in [("C8b cycles", False, cycles, 0), ("C8b zombie control", True, 3, 100)]:
        sub = work / ("leak" if leak else "cycles")
        module, problems = build_module(cosmo, gen_debug, sub, leak=leak, quiet=True)
        if module is None:
            checks[f"{arch} {label}: module builds"] = (False, problems)
            continue
        lines, status = boot_lines(cosmo, sub, [(f"tests/{MODULE}.ko", module)], timeout,
                                   cmdline=f"module.cycle=tests/{MODULE}.ko:{count}:{hold}")
        result = next((l for l in lines if "modcycle:" in l), "no modcycle line")
        if leak:
            # The leaked reference keeps the module's release code needed: every unload is -EBUSY (a zombie).
            zombie = re.search(r"unload failures (\d+)", result)
            checks[f"{arch} {label}: {result.split('modcycle: ')[-1][:160]}"] = (
                zombie is not None and int(zombie.group(1)) == count and "FAIL" in result, [])
            continue
        checks[f"{arch} {label}: {result.split('modcycle: ')[-1][:220]}"] = (re.search(rf"{count} cycles \(hold \d+ ms\): PASS", result) is not None, [])
        classes = re.search(r"lockdep classes (\d+) -> (\d+)", result)
        if classes:
            # Reported, not judged (proposals/module-cycle/README.md): lockdep names a callback's class after its
            # address, so each new load address of the module's timer callback adds one.
            checks[f"{arch} {label} (note): lockdep classes {classes.group(1)} -> {classes.group(2)} over the cycles"] = (True, [])
        common_boot_checks(arch, lines, status, checks, label)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cosmoos", default=str(Path.home() / "dev" / "CosmoOS"))
    parser.add_argument("--arch", choices=["x86_64", "aarch64"], default="aarch64")
    parser.add_argument("--no-boot", action="store_true", help="skip the boots")
    parser.add_argument("--cycles", type=int, default=0, help="C8b: load/unload cycles through CosmoOS's module-cycle hook")
    parser.add_argument("--timeout", type=int, default=1200)
    args = parser.parse_args()
    root = Path(args.cosmoos).expanduser().resolve()
    c4.COSMO = root
    status_before = c1.git_status(root)
    c1.require_compiler()
    checks = {}
    negative_cases(checks)
    work = c1.CEESAFE_ROOT / "out" / "cosmoos" / "c8"
    gen = work / "gen"
    gen.mkdir(parents=True, exist_ok=True)
    c1.run([c1.CEESAFEC, "build", "--profile", "freestanding", "--no-float", "--emit", "c", "-o", gen, *PACKAGE], cwd=c1.CEESAFE_ROOT)
    host = c1.Cosmo(root, args.arch, c1.CEESAFE_ROOT / "out" / "cosmoos" / f"{args.arch}-release")
    host_test(host, root, gen, work, checks)
    if not args.no_boot:
        boot_at_load(root, args.arch, gen, args.timeout, checks)
        if args.cycles:
            boot_cycles(root, args.arch, gen, args.cycles, args.timeout, checks)
    checks["CosmoOS working tree unchanged"] = (c1.git_status(root) == status_before, [])
    for name, (ok, details) in checks.items():
        print(f"[c8] {'PASS' if ok else 'FAIL'}  {name}")
        for detail in details[:10]:
            print(f"[c8]        {detail}")
    return 0 if all(ok for ok, _ in checks.values()) else 1


if __name__ == "__main__":
    sys.exit(main())
