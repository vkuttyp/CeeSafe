/* A decimal f * 10^e. */
typedef struct cee_decimal { uint64_t f; int e; } cee_decimal;

/* Schubfach's rounding of g * cp / 2^127 to an odd-sticky value (paper §9.8.3). */
static uint64_t cee_rop64(uint64_t g1, uint64_t g0, uint64_t cp) {
    uint64_t x1 = cee_umulh(g0, cp);
    uint64_t y0 = g1 * cp;
    uint64_t y1 = cee_umulh(g1, cp);
    uint64_t z = (y0 >> 1) + x1;
    uint64_t vbp = y1 + (z >> 63);
    return vbp | (((z & 0x7FFFFFFFFFFFFFFFu) + 0x7FFFFFFFFFFFFFFFu) >> 63);
}

static uint32_t cee_rop32(uint64_t g, uint64_t cp) {
    uint64_t x1 = cee_umulh(g, cp);
    uint64_t vbp = x1 >> 31;
    return (uint32_t)(vbp | (((x1 & 0xFFFFFFFFu) + 0xFFFFFFFFu) >> 32));
}

/*
 * v = c * 2^q. As in the paper's Java code, except that a result may have one digit: Java's Double.toString needs
 * two, so that code tries one digit fewer only from s >= 100 and scales the tiniest subnormals by 10; ECMAScript wants
 * the shortest, so this tries it from s >= 10 (5e-324, not 4.9e-324). The argument for one digit fewer (paper §9.3)
 * does not depend on how many digits s has.
 */
static cee_decimal cee_to_decimal64(int q, uint64_t c) {
    uint64_t out = c & 1u;
    uint64_t cb = c << 2, cbr = cb + 2, cbl;
    int k;
    if (c != (UINT64_C(1) << 52) || q == -1074) {
        cbl = cb - 2; /* regular spacing */
        k = cee_flog10pow2(q);
    } else {
        cbl = cb - 1; /* the lower neighbour is closer, at a power of two */
        k = cee_flog10threequarterspow2(q);
    }
    int h = q + cee_flog2pow10(-k) + 2;
    uint64_t g1 = cee_g[k - CEE_K_MIN][0], g0 = cee_g[k - CEE_K_MIN][1];
    uint64_t vb = cee_rop64(g1, g0, cb << h);
    uint64_t vbl = cee_rop64(g1, g0, cbl << h);
    uint64_t vbr = cee_rop64(g1, g0, cbr << h);
    uint64_t s = vb >> 2;
    if (s >= 10) {
        /* One digit fewer: s' = floor(s / 10), with u' = 10 s' and w' = u' + 10. */
        uint64_t sp10 = 10 * cee_umulh(s, UINT64_C(115292150460684698) << 4);
        uint64_t tp10 = sp10 + 10;
        bool upin = vbl + out <= sp10 << 2;
        bool wpin = (tp10 << 2) + out <= vbr;
        if (upin != wpin) return (cee_decimal){ upin ? sp10 : tp10, k };
    }
    uint64_t t = s + 1;
    bool uin = vbl + out <= s << 2;
    bool win = (t << 2) + out <= vbr;
    if (uin != win) return (cee_decimal){ uin ? s : t, k };
    /* Both in the interval: the nearer to v, and the even one on a tie. */
    int64_t cmp = (int64_t)vb - (int64_t)((s + t) << 1);
    return (cee_decimal){ cmp < 0 || (cmp == 0 && (s & 1u) == 0) ? s : t, k };
}

static cee_decimal cee_to_decimal32(int q, uint32_t c) {
    uint64_t out = c & 1u;
    uint64_t cb = (uint64_t)c << 2, cbr = cb + 2, cbl;
    int k;
    if (c != (UINT32_C(1) << 23) || q == -149) {
        cbl = cb - 2;
        k = cee_flog10pow2(q);
    } else {
        cbl = cb - 1;
        k = cee_flog10threequarterspow2(q);
    }
    int h = q + cee_flog2pow10(-k) + 33;
    uint64_t g = cee_g[k - CEE_K_MIN][0] + 1;
    uint64_t vb = cee_rop32(g, cb << h);
    uint64_t vbl = cee_rop32(g, cbl << h);
    uint64_t vbr = cee_rop32(g, cbr << h);
    uint64_t s = vb >> 2;
    if (s >= 10) {
        uint64_t sp10 = 10 * ((s * UINT64_C(1717986919)) >> 34);
        uint64_t tp10 = sp10 + 10;
        bool upin = vbl + out <= sp10 << 2;
        bool wpin = (tp10 << 2) + out <= vbr;
        if (upin != wpin) return (cee_decimal){ upin ? sp10 : tp10, k };
    }
    uint64_t t = s + 1;
    bool uin = vbl + out <= s << 2;
    bool win = (t << 2) + out <= vbr;
    if (uin != win) return (cee_decimal){ uin ? s : t, k };
    int64_t cmp = (int64_t)vb - (int64_t)((s + t) << 1);
    return (cee_decimal){ cmp < 0 || (cmp == 0 && (s & 1u) == 0) ? s : t, k };
}

/* Lays out sign * 0.d1...dk * 10^n as ECMAScript does; `d` holds f * 10^e. Returns the text written into buf. */
static cee_str cee_layout(bool negative, cee_decimal d, uint8_t *buf) {
    uint8_t digits[20];
    int count = 0;
    uint64_t f = d.f;
    int e = d.e;
    while (f % 10 == 0) { f /= 10; e++; }
    for (uint64_t r = f; r != 0; r /= 10) digits[count++] = (uint8_t)('0' + r % 10);
    /* digits[] holds them last first */
    int n = e + count;
    uint8_t *p = buf;
    if (negative) *p++ = '-';
    if (count <= n && n <= 21) {
        for (int i = count - 1; i >= 0; i--) *p++ = digits[i];
        for (int i = 0; i < n - count; i++) *p++ = '0';
    } else if (0 < n && n <= 21) {
        for (int i = count - 1; i >= 0; i--) {
            *p++ = digits[i];
            if (i == count - n) *p++ = '.';
        }
    } else if (-6 < n && n <= 0) {
        *p++ = '0';
        *p++ = '.';
        for (int i = 0; i < -n; i++) *p++ = '0';
        for (int i = count - 1; i >= 0; i--) *p++ = digits[i];
    } else {
        *p++ = digits[count - 1];
        if (count > 1) {
            *p++ = '.';
            for (int i = count - 2; i >= 0; i--) *p++ = digits[i];
        }
        int x = n - 1;
        *p++ = 'e';
        *p++ = x < 0 ? '-' : '+';
        unsigned magnitude = (unsigned)(x < 0 ? -x : x);
        uint8_t exponent[4];
        int length = 0;
        do { exponent[length++] = (uint8_t)('0' + magnitude % 10); magnitude /= 10; } while (magnitude != 0);
        while (length > 0) *p++ = exponent[--length];
    }
    return (cee_str){ .ptr = buf, .len = (uint64_t)(p - buf) };
}

static cee_str cee_special(const char *text, uint8_t *buf) {
    uint64_t length = 0;
    while (text[length] != '\0') { buf[length] = (uint8_t)text[length]; length++; }
    return (cee_str){ .ptr = buf, .len = length };
}

cee_str ceesafe_format_f64(double value, uint8_t *buf) {
    uint64_t bits = cee_f64_bits(value);
    bool negative = (bits >> 63) != 0;
    uint64_t fraction = bits & ((UINT64_C(1) << 52) - 1);
    int biased = (int)((bits >> 52) & 0x7FF);
    if (biased == 0x7FF) return cee_special(fraction != 0 ? "NaN" : negative ? "-Infinity" : "Infinity", buf);
    if (biased != 0) {
        int mq = 1075 - biased; /* v = c * 2^-mq */
        uint64_t c = (UINT64_C(1) << 52) | fraction;
        if (0 < mq && mq < 53) {
            uint64_t f = c >> mq; /* an integer below 2^53 prints exactly: its digits are the shortest */
            if (f << mq == c) return cee_layout(negative, (cee_decimal){ f, 0 }, buf);
        }
        return cee_layout(negative, cee_to_decimal64(-mq, c), buf);
    }
    if (fraction != 0) {
        return cee_layout(negative, cee_to_decimal64(-1074, fraction), buf);
    }
    return cee_special("0", buf); /* both zeros, as ECMAScript prints them */
}

cee_str ceesafe_format_f32(float value, uint8_t *buf) {
    uint32_t bits = cee_f32_bits(value);
    bool negative = (bits >> 31) != 0;
    uint32_t fraction = bits & ((UINT32_C(1) << 23) - 1);
    int biased = (int)((bits >> 23) & 0xFF);
    if (biased == 0xFF) return cee_special(fraction != 0 ? "NaN" : negative ? "-Infinity" : "Infinity", buf);
    if (biased != 0) {
        int mq = 150 - biased;
        uint32_t c = (UINT32_C(1) << 23) | fraction;
        if (0 < mq && mq < 24) {
            uint32_t f = c >> mq;
            if (f << mq == c) return cee_layout(negative, (cee_decimal){ f, 0 }, buf);
        }
        return cee_layout(negative, cee_to_decimal32(-mq, c), buf);
    }
    if (fraction != 0) {
        return cee_layout(negative, cee_to_decimal32(-149, fraction), buf);
    }
    return cee_special("0", buf);
}
