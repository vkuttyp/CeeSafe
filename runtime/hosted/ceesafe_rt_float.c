/*
 * ceesafe_rt_float.c - printing f32 and f64 (type-system.md §35.7; ADR 0011 §3.6).
 *
 * The text of a float is the shortest decimal that reads back as the same value, the one nearest to it when several
 * are equally short (ties to an even last digit), laid out as ECMAScript's Number::toString (ECMA-262 §6.1.6.1.20).
 * The digits come from Schubfach (R. Giulietti, "The Schubfach way to render doubles", 2020): one 126-bit
 * multiplication by a power of ten from a table for each candidate, with integers only, so no libc formatting,
 * whose last digit CosmoOS does not round exactly, and no long double or __int128 (MSVC has neither of use).
 *
 * The generated program links this file only if it prints a float.
 */
#define CEE_FLOATS 1
#include "ceesafe/rt.h"

/* The high 64 bits of a * b, from 32-bit halves. */
static uint64_t cee_umulh(uint64_t a, uint64_t b) {
    uint64_t a0 = a & 0xFFFFFFFFu, a1 = a >> 32, b0 = b & 0xFFFFFFFFu, b1 = b >> 32;
    uint64_t p00 = a0 * b0, p01 = a0 * b1, p10 = a1 * b0, p11 = a1 * b1;
    uint64_t middle = (p00 >> 32) + (p01 & 0xFFFFFFFFu) + (p10 & 0xFFFFFFFFu);
    return p11 + (p01 >> 32) + (p10 >> 32) + (middle >> 32);
}

/* floor(x / 2^s) for a signed x, without C's implementation-defined right shift of negative values. */
static int cee_floor_shift(int64_t x, int s) {
    return (int)(x >= 0 ? x >> s : -(((-x) - 1) >> s) - 1);
}

/* floor(log10(2^q)), floor(log10(3/4 * 2^q)) and floor(log2(10^e)), exact over the ranges used (checked by the
   script that made the table). */
static int cee_flog10pow2(int q) { return cee_floor_shift((int64_t)q * 661971961083, 41); }
static int cee_flog10threequarterspow2(int q) { return cee_floor_shift((int64_t)q * 661971961083 - 274743187321, 41); }
static int cee_flog2pow10(int e) { return cee_floor_shift((int64_t)e * 913124641741, 38); }

