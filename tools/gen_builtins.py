#!/usr/bin/env python3
"""Writes src/hir/builtins.cee: the reference's BuiltinFunction members (Hir/Hir.cs), each as a function returning
its declaration index, which HirExpr.BuiltinCall stores. The source is a Nova checkout at the pinned tag, which must
be clean.

usage: python3 tools/gen_builtins.py [--nova PATH]   (default ~/Nova; formats with $NOVAC, default the pinned
       ~/.nova/0.6.0/bin/novac; review the diff)
"""

import argparse
import os
import re
import subprocess
import sys


def members(nova):
    text = open(os.path.join(nova, "src/Nova.Compiler/Hir/Hir.cs"), encoding="utf-8").read()
    body = re.search(r"public enum BuiltinFunction\s*\{(.*?)\n\}", text, re.S).group(1)
    names = []
    for line in body.splitlines():
        line = re.sub(r"//.*", "", line).strip()
        for part in line.split(","):
            part = part.strip()
            if part:
                if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", part):
                    sys.exit(f"unexpected BuiltinFunction member text: {part!r}")
                names.append(part)
    return names


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--nova", default=os.path.expanduser("~/Nova"))
    args = parser.parse_args()
    head = subprocess.run(["git", "-C", args.nova, "describe", "--tags", "--always"], capture_output=True, text=True,
                          check=True).stdout.strip()
    dirty = subprocess.run(["git", "-C", args.nova, "status", "--porcelain", "src/Nova.Compiler/Hir"],
                           capture_output=True, text=True, check=True).stdout.strip()
    if dirty:
        sys.exit(f"{args.nova} has local changes under src/Nova.Compiler/Hir")
    names = members(args.nova)
    out = [
        "// The reference's BuiltinFunction (Hir/Hir.cs), by declaration index: what HirExpr.BuiltinCall stores.",
        f"// GENERATED by tools/gen_builtins.py from Nova {head}: rerun it, do not edit.",
        "",
        f"fn builtinFunctionCount() -> u32 => {len(names)};",
        "",
    ]
    for index, name in enumerate(names):
        out.append(f"fn bf{name}() -> u32 => {index};")
    # The members' names, as NirPrinter writes a NirBuiltin (`{b.Function}`).
    out.append("")
    out.append("/// The member's name, by declaration index.")
    out.append("fn builtinFunctionName(index: u32) -> StringView => match (index) {")
    for index, name in enumerate(names[:-1]):
        out.append(f'    {index} => "{name}",')
    out.append(f'    _ => "{names[-1]}",')
    out.append("};")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "hir", "builtins.cee")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    novac = os.environ.get("NOVAC", os.path.expanduser("~/.nova/0.6.0/bin/novac"))
    subprocess.run([novac, "fmt", path], check=True)
    print(f"{len(names)} builtin functions from {head}")


if __name__ == "__main__":
    main()
