#!/usr/bin/env python3
"""Black-box corpus runner for the CeeSafe port (ROADMAP P0).

Runs Nova's test corpus (tests/corpus, format in Nova's docs/testing.md §3) against any compiler executable that
speaks novac's command line: today the pinned novac, later each generation of ceesafec. It checks the corpus's own
expectations (`// error[N0100]` annotations, `.ast`/`.hir`/`.c`/`.h` snapshots, `// expect-stdout:` directives,
explanation snapshots), independently of any compiler. With --reference it also runs a second compiler on the same
commands and reports every observable difference (status, stdout, stderr, emitted files).

Normalisation is deliberately narrow and listed in NORMALISATIONS; it never removes a diagnostic, a check, a drop or a
panic location.

usage: tools/run_corpus.py --compiler PATH [--reference PATH] [--corpus DIR] [--family F]... [--filter TEXT]
                           [--jobs N] [--timeout S] [--cc CC] [--cflag=FLAG]... [--with FILE]... [--report FILE] [-v]

Write C flags as --cflag=-O2: argparse reads a separate `-O2` as an option of its own.
--with adds source files to every check and build (for tests of a library such as CeeSafe's src/support/); a
diagnostic in one of them is a failure.
"""

import argparse
import concurrent.futures
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time

RUNNER = "tools/run_corpus.py v1"

# Every rewrite applied before comparing text. Version this list: a change here changes what "equal" means.
NORMALISATIONS = [
    # The generated-C banner names the compiler and its version (c-backend.md §1).
    ("generated-by banner", re.compile(r"^/\* Generated by \S+ \S+\. Do not edit\.( .*)?\*/$", re.M),
     r"/* Generated by <compiler> <version>. Do not edit.\1*/"),
    # Command-line errors start with the executable's name.
    ("program name", re.compile(r"^(?:novac|ceesafec): ", re.M), "<compiler>: "),
]

FAMILIES = [
    "parse-pass", "parse-fail", "check-pass", "check-fail", "run-pass", "run-fail", "emit-c", "ffi", "freestanding",
    "bounds-checks", "overflow-checks", "placement", "closure-calls",
]

# Explanation families: the option that prints the report, and the snapshot's extension.
EXPLAIN = {
    "bounds-checks": ("--explain-bounds-checks", ".bce"),
    "overflow-checks": ("--explain-overflow-checks", ".oce"),
    "placement": ("--explain-allocations", ".alloc"),
    "closure-calls": ("--explain-closure-calls", ".calls"),
}

ANNOTATION = re.compile(r"// error\[(N\d{4})\](?:@(\d+))?")
DIRECTIVE = re.compile(r"// expect-(stdout|exit|panic):(?: (.*))?$")
ABORT_EXIT = 134  # 128 + SIGABRT


def normalise(text):
    for _, pattern, replacement in NORMALISATIONS:
        text = pattern.sub(replacement, text)
    return text.replace("\r\n", "\n")


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def lines_of(text):
    return text.replace("\r\n", "\n").split("\n")


def compile_options(text):
    """The corpus's per-file options (CorpusTests.ProfileOf, NoFloatOf, KernelOf)."""
    stripped = {line.strip() for line in lines_of(text)}
    options = []
    if "// profile: freestanding" in stripped:
        options += ["--profile", "freestanding"]
    if "// option: no-float" in stripped:
        options.append("--no-float")
    if "// option: kernel cosmoos" in stripped:
        options += ["--kernel", "cosmoos"]
    return options


def annotations(text):
    result = []
    for number, line in enumerate(lines_of(text), 1):
        for m in ANNOTATION.finditer(line):
            result.append((number, m.group(1), int(m.group(2)) if m.group(2) else None))
    return result


def expectations(text):
    """RunCorpusTests.ParseExpectations: stdout lines, exit status, panic reason and line."""
    stdout, exit_code, panic, panic_line = [], 0, None, 0
    for number, line in enumerate(lines_of(text), 1):
        m = DIRECTIVE.search(line)
        if not m:
            continue
        kind, value = m.group(1), m.group(2) or ""
        if kind == "stdout":
            stdout.append(value + "\n")
        elif kind == "exit":
            exit_code = int(value)
        else:
            panic, panic_line, exit_code = value, number, ABORT_EXIT
    return "".join(stdout), exit_code, panic, panic_line


class Outcome:
    """What one command did: the observable result compared between compilers."""

    def __init__(self, argv, status, stdout, stderr, files, seconds):
        self.argv, self.status, self.stdout, self.stderr = argv, status, stdout, stderr
        self.files, self.seconds = files, seconds

    def key(self):
        return (self.status, normalise(self.stdout), normalise(self.stderr),
                tuple(sorted((k, normalise(v)) for k, v in self.files.items())))


class Runner:
    def __init__(self, args, compiler):
        self.args, self.compiler = args, compiler
        self.corpus = args.corpus

    def command(self, argv, out_dir=None, collect=()):
        """Runs the compiler from the corpus root, so paths in diagnostics and panics are corpus-relative."""
        full = [self.compiler] + argv
        start = time.monotonic()
        try:
            p = subprocess.run(full, cwd=self.corpus, capture_output=True, timeout=self.args.timeout,
                               env=self.env())
            status, stdout, stderr = p.returncode, p.stdout.decode("utf-8", "replace"), p.stderr.decode("utf-8", "replace")
        except subprocess.TimeoutExpired:
            status, stdout, stderr = "timeout", "", ""
        files = {}
        for name in collect:
            path = os.path.join(out_dir, name)
            if os.path.isfile(path):
                files[name] = read(path)
        return Outcome(argv, status, stdout, stderr, files, time.monotonic() - start)

    def env(self):
        env = dict(os.environ)
        if self.args.cc:
            env["CC"] = self.args.cc
        return env

    def execute(self, exe):
        start = time.monotonic()
        try:
            p = subprocess.run([exe], cwd=self.corpus, capture_output=True, timeout=self.args.timeout)
            status, stdout, stderr = p.returncode, p.stdout.decode("utf-8", "replace"), p.stderr.decode("utf-8", "replace")
        except subprocess.TimeoutExpired:
            status, stdout, stderr = "timeout", "", ""
        if isinstance(status, int) and status < 0:
            status = 128 - status  # killed by a signal, as a shell reports it
        return Outcome([exe], status, stdout, stderr, {}, time.monotonic() - start)

    def cflags(self):
        result = []
        for flag in self.args.cflag:
            result += ["--cflag", flag]
        return result


def diagnostics_of(outcome, path, problems):
    """(line, code, column) of the JSON diagnostics in `path`; others are problems."""
    try:
        document = json.loads(outcome.stdout)
    except json.JSONDecodeError:
        problems.append(f"no JSON diagnostics (status {outcome.status}): {outcome.stderr.strip()[:300]}")
        return []
    result = []
    for d in document.get("diagnostics", []):
        where = f"{d.get('file')}:{d['start']['line']}:{d['start']['column']}"
        if d.get("file") != path:
            problems.append(f"diagnostic outside the file: {d['code']} at {where}: {d.get('message')}")
            continue
        result.append((d["start"]["line"], d["code"], d["start"]["column"], d.get("message", "")))
    return result


def match_annotations(expected, actual, problems):
    remaining = list(actual)
    for line, code, column in expected:
        index = next((i for i, a in enumerate(remaining)
                      if a[0] == line and a[1] == code and (column is None or a[2] == column)), None)
        if index is None:
            problems.append(f"missing {code} at line {line}" + (f":{column}" if column else ""))
        else:
            remaining.pop(index)
    for line, code, column, message in remaining:
        problems.append(f"unexpected {code} at {line}:{column}: {message}")


def compare_snapshot(actual, snapshot, problems, label):
    if not os.path.isfile(snapshot):
        problems.append(f"missing snapshot {os.path.basename(snapshot)}")
        return
    if normalise(actual) != normalise(read(snapshot)):
        problems.append(f"{label} differs from {os.path.basename(snapshot)}")


def run_test(runner, family, path, work):
    """Runs one corpus file. Returns (problems, skipped reason or None, outcomes)."""
    text = read(os.path.join(runner.corpus, path))
    stem = os.path.join(runner.corpus, path[:-len(".nova")])
    options = compile_options(text)
    extra = runner.args.with_files
    problems, outcomes = [], []

    def cmd(argv, out_dir=None, collect=()):
        o = runner.command(argv, out_dir, collect)
        outcomes.append(o)
        return o

    if family in ("parse-pass", "parse-fail"):
        o = cmd(["parse", "--diagnostics-format=json", path])
        found = diagnostics_of(o, path, problems)
        if family == "parse-pass":
            problems += [f"unexpected {c} at {l}:{col}: {m}" for l, c, col, m in found]
            dump = cmd(["parse", "--dump-ast", path])
            compare_snapshot(dump.stdout, stem + ".ast", problems, "AST dump")
        else:
            expected = annotations(text)
            if not expected:
                problems.append("a failing test must annotate at least one expected error")
            match_annotations(expected, found, problems)

    elif family in ("check-pass", "check-fail"):
        if family == "check-fail":
            parsed = diagnostics_of(cmd(["parse", "--diagnostics-format=json", path]), path, problems)
            problems += [f"check-fail input does not parse: {c} at {l}:{col}" for l, c, col, _ in parsed]
        o = cmd(["check", "--diagnostics-format=json"] + options + [path] + extra)
        found = diagnostics_of(o, path, problems)
        if family == "check-pass":
            problems += [f"unexpected {c} at {l}:{col}: {m}" for l, c, col, m in found]
            dump = cmd(["check", "--dump-hir"] + options + [path] + extra)
            compare_snapshot(dump.stdout, stem + ".hir", problems, "HIR dump")
        else:
            expected = annotations(text)
            if not expected:
                problems.append("a failing test must annotate at least one expected error")
            match_annotations(expected, found, problems)

    elif family in ("run-pass", "run-fail", "ffi"):
        exe = os.path.join(work, "program")
        inputs = [path] + extra
        if family == "ffi":
            inputs.append(path[:-len(".nova")] + ".c")
            # NAME.types.h is found from the corpus family's directory (FfiTests copies it beside the C).
            inputs_flags = ["--cflag", "-I" + os.path.dirname(os.path.join(runner.corpus, path))]
        else:
            inputs_flags = []
        o = cmd(["build"] + options + runner.cflags() + inputs_flags + inputs + ["-o", exe])
        if o.status != 0:
            problems.append(f"build failed (status {o.status}): {o.stderr.strip()[:500]}")
        else:
            run = runner.execute(exe)
            outcomes.append(run)
            stdout, exit_code, panic, panic_line = expectations(text)
            if run.stdout.replace("\r\n", "\n") != stdout:
                problems.append(f"stdout differs:\n--- expected\n{stdout}--- actual\n{run.stdout}")
            if run.status != exit_code:
                problems.append(f"exit {run.status}, expected {exit_code}; stderr: {run.stderr.strip()[:300]}")
            if panic is not None and not run.stderr.startswith(f"nova panic: {panic} at {path}:{panic_line}:"):
                problems.append(f"panic message differs: {run.stderr.strip()[:300]}")
        if family == "ffi":
            out = os.path.join(work, "c")
            e = cmd(["build", "--emit", "c"] + inputs + ["-o", out], out, ["nova_exports.h"])
            snapshot = stem + ".h"
            header = e.files.get("nova_exports.h")
            if header is None and os.path.isfile(snapshot):
                problems.append("no nova_exports.h, but a .h snapshot exists")
            elif header is not None:
                compare_snapshot(header, snapshot, problems, "nova_exports.h")

    elif family == "emit-c":
        out = os.path.join(work, "c")
        flags = []
        if "// emit-option: line-directives" in text:
            flags.append("--line-directives")
        if "// emit-option: flat" in text:
            flags.append("--flat-c")
        o = cmd(["build", "--emit", "c"] + options + flags + [path, "-o", out], out, ["main.c"])
        if "main.c" not in o.files:
            problems.append(f"no main.c (status {o.status}): {o.stderr.strip()[:500]}")
        else:
            compare_snapshot(o.files["main.c"], stem + ".c", problems, "main.c")

    elif family == "freestanding":
        obj = os.path.join(work, "program.o")
        o = cmd(["build", "--profile", "freestanding", "--emit", "obj"] + runner.cflags() + [path, "-o", obj])
        if o.status != 0:
            problems.append(f"freestanding object build failed (status {o.status}): {o.stderr.strip()[:500]}")
        if not problems:
            return problems, "object builds; FreestandingTests' symbol and section checks are not ported", \
                outcomes

    elif family in EXPLAIN:
        option, extension = EXPLAIN[family]
        o = cmd(["build", option] + options + runner.cflags() + [path, "-o", os.path.join(work, "program")])
        if o.status != 0:
            problems.append(f"build failed (status {o.status}): {o.stderr.strip()[:500]}")
        else:
            compare_snapshot(o.stdout, stem + extension, problems, option)

    return problems, None, outcomes


def corpus_files(corpus, families, text_filter):
    for family in families:
        directory = os.path.join(corpus, family)
        for name in sorted(os.listdir(directory)):
            if name.endswith(".nova"):
                path = f"{family}/{name}"
                if not text_filter or text_filter in path:
                    yield family, path


def resolve(program):
    path = shutil.which(os.path.expanduser(program))
    if not path:
        sys.exit(f"run_corpus: no executable {program}")
    return os.path.abspath(path)


def version_of(compiler):
    p = subprocess.run([compiler, "--version"], capture_output=True, text=True)
    return (p.stdout or p.stderr).strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--compiler", required=True, help="compiler under test")
    parser.add_argument("--reference", help="a second compiler whose outcomes must be identical")
    parser.add_argument("--corpus", default=os.path.expanduser("~/Nova/tests/corpus"))
    parser.add_argument("--family", action="append", choices=FAMILIES, help="repeatable; default: all")
    parser.add_argument("--filter", help="only files whose corpus path contains this text")
    parser.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    parser.add_argument("--timeout", type=float, default=60.0, help="seconds per command or program run")
    parser.add_argument("--cc", help="C compiler (sets $CC for the compiler)")
    parser.add_argument("--cflag", action="append", default=[], help="extra C flag for builds (repeatable)")
    parser.add_argument("--with", dest="with_files", action="append", default=[],
                        help="extra source file for every check and build (repeatable)")
    parser.add_argument("--report", help="write a JSON report here")
    parser.add_argument("-v", "--verbose", action="store_true", help="print every failure's details")
    args = parser.parse_args()
    args.corpus = os.path.abspath(args.corpus)
    args.with_files = sorted(os.path.abspath(f) for f in args.with_files)

    compiler = resolve(args.compiler)
    reference = resolve(args.reference) if args.reference else None
    families = args.family or FAMILIES
    tests = list(corpus_files(args.corpus, families, args.filter))
    print(f"{RUNNER}: {len(tests)} files; compiler {compiler} ({version_of(compiler)})"
          + (f"; reference {reference} ({version_of(reference)})" if reference else ""))

    def one(item):
        family, path = item
        with tempfile.TemporaryDirectory(prefix="ceesafe-corpus-") as work:
            problems, skipped, outcomes = run_test(Runner(args, compiler), family, path, work)
            ref_problems = []
            if reference:
                with tempfile.TemporaryDirectory(prefix="ceesafe-corpus-") as ref_work:
                    # Same commands, same relative output names, so emitted file names compare equal.
                    _, _, ref_outcomes = run_test(Runner(args, reference), family, path, ref_work)
                if len(ref_outcomes) != len(outcomes):
                    ref_problems.append("the reference ran a different number of commands")
                for mine, theirs in zip(outcomes, ref_outcomes):
                    if mine.key() != theirs.key():
                        what = [n for n, a, b in (("status", mine.status, theirs.status),
                                                  ("stdout", normalise(mine.stdout), normalise(theirs.stdout)),
                                                  ("stderr", normalise(mine.stderr), normalise(theirs.stderr)))
                                if a != b]
                        if mine.key()[3] != theirs.key()[3]:
                            what.append("emitted files")
                        argv = " ".join(os.path.basename(a) if a.startswith(work) else a for a in mine.argv)
                        ref_problems.append(f"differs from the reference ({', '.join(what)}): {argv}")
        seconds = sum(o.seconds for o in outcomes)
        return family, path, problems, skipped, ref_problems, seconds

    results = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for result in pool.map(one, tests):
            results.append(result)
            family, path, problems, skipped, ref_problems, _ = result
            if problems or ref_problems:
                print(f"FAIL {path}")
                for p in (problems + ref_problems) if args.verbose else (problems + ref_problems)[:3]:
                    print("    " + p.replace("\n", "\n    "))

    summary = {}
    for family, path, problems, skipped, ref_problems, _ in results:
        s = summary.setdefault(family, {"pass": 0, "fail": 0, "partial": 0, "reference-diff": 0})
        if problems:
            s["fail"] += 1
        elif skipped:
            s["partial"] += 1
        else:
            s["pass"] += 1
        if ref_problems:
            s["reference-diff"] += 1
    print()
    print(f"{'family':<18}{'pass':>6}{'fail':>6}{'partial':>9}" + (f"{'ref-diff':>10}" if reference else ""))
    for family in families:
        s = summary.get(family, {"pass": 0, "fail": 0, "partial": 0, "reference-diff": 0})
        print(f"{family:<18}{s['pass']:>6}{s['fail']:>6}{s['partial']:>9}"
              + (f"{s['reference-diff']:>10}" if reference else ""))
    partial_reasons = sorted({r[3] for r in results if r[3] and not r[2]})
    for reason in partial_reasons:
        print(f"partial: {reason}")

    if args.report:
        report = {
            "runner": RUNNER,
            "compiler": {"path": compiler, "version": version_of(compiler)},
            "reference": {"path": reference, "version": version_of(reference)} if reference else None,
            "corpus": args.corpus, "cc": args.cc, "cflags": args.cflag,
            "normalisations": [name for name, _, _ in NORMALISATIONS],
            "summary": summary,
            "results": [{"path": path, "family": family, "problems": problems, "partial": skipped,
                         "reference": ref_problems, "seconds": round(seconds, 3)}
                        for family, path, problems, skipped, ref_problems, seconds in results],
        }
        os.makedirs(os.path.dirname(os.path.abspath(args.report)), exist_ok=True)
        with open(args.report, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=1)
            f.write("\n")

    failed = any(r[2] or r[4] for r in results)
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
