#!/usr/bin/env python3
"""Writes src/library/sources.cee: the libraries ceesafec embeds, from CeeSafe's lib/ sources (Decision 0008).

lib/core, lib/std and lib/kernel, each in ordinal path order, with line endings made "\\n". Each file is a run of
string literals; its path is "lib/core/NAME.cee" and so on, which marks it as library code. The libraries came from
Nova v0.6.0 (the reference's CoreLibrary.cs) under CeeSafe's names; since Nova is no longer developed, lib/ is the
source of truth and is edited here.

usage: python3 tools/gen_library.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import os
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

GROUPS = (("lib/core/", 0), ("lib/std/", 1), ("lib/kernel/", 2))


def literal(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append("\\u{%X}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main():
    files = []
    for prefix, group in GROUPS:
        directory = os.path.join(ROOT, prefix)
        for name in sorted(n for n in os.listdir(directory) if n.endswith(".cee")):
            with open(os.path.join(directory, name), encoding="utf-8-sig", newline="") as f:
                text = f.read().replace("\r\n", "\n").replace("\r", "\n")
            files.append((prefix + name, group, text))
    paths = "\n".join(f"    {k} => \"{p}\"," for k, (p, _, _) in enumerate(files[:-1]))
    groups = "\n".join(f"    {k} => {g}," for k, (_, g, _) in enumerate(files[:-1]))
    last = files[-1]
    # C requires compilers to accept string literals of only 4,095 bytes (C11 §5.2.4.1; novac's -pedantic warns past
    # that), so each file is split into chunks of at most 4,000 bytes of UTF-8, at character boundaries.
    chunks = []
    for k, (_, _, t) in enumerate(files):
        current, size = [], 0
        for ch in t:
            n = len(ch.encode("utf-8"))
            if size + n > 4000:
                chunks.append((k, "".join(current)))
                current, size = [], 0
            current.append(ch)
            size += n
        chunks.append((k, "".join(current)))
    counts = [sum(1 for f, _ in chunks if f == k) for k in range(len(files))]
    firsts, total = [], 0
    for n in counts:
        firsts.append(total)
        total += n
    count_arms = "\n".join(f"    {k} => {n}," for k, n in enumerate(counts[:-1]))
    first_arms = "\n".join(f"    {k} => {f}," for k, f in enumerate(firsts[:-1]))
    chunk_arms = "\n".join(f"    {j} => {literal(text)}," for j, (_, text) in enumerate(chunks[:-1]))
    source = f"""// The libraries ceesafec embeds: lib/core, lib/std and lib/kernel, each in ordinal path order. GENERATED by
// tools/gen_library.py from lib/: edit lib/ and rerun it, never this file. Each file is a run of chunks of at most
// 4,000 bytes, since C compilers need accept string literals of only 4,095 (C11 §5.2.4.1).

fn libraryFileCount() -> usize => {len(files)};

/// The file's path, "lib/core/NAME.cee" and so on; the prefix marks library code.
fn libraryPath(k: usize) -> StringView => match (k) {{
{paths}
    _ => "{last[0]}",
}};

/// 0 for lib/core, 1 for lib/std (hosted), 2 for lib/kernel (freestanding with --kernel).
fn libraryGroup(k: usize) -> u32 => match (k) {{
{groups}
    _ => {last[1]},
}};

fn libraryChunkCount(k: usize) -> usize => match (k) {{
{count_arms}
    _ => {counts[-1]},
}};

fn libraryFirstChunk(k: usize) -> usize => match (k) {{
{first_arms}
    _ => {firsts[-1]},
}};

fn libraryChunk(j: usize) -> StringView => match (j) {{
{chunk_arms}
    _ => {literal(chunks[-1][1])},
}};

/// The whole text of file `k`.
fn libraryText(k: usize) -> Result<Vector<u8>, AllocError> {{
    var text = Vector<u8>.create();
    for (j in 0..libraryChunkCount(k)) {{
        appendText(mut text, libraryChunk(libraryFirstChunk(k) + j))?;
    }}
    return Ok(text);
}}
"""
    path = os.path.join(ROOT, "src", "library", "sources.cee")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    formatter = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([formatter, "fmt", path], check=True)
    print(f"gen_library: wrote {path} ({len(files)} files from lib/)")


if __name__ == "__main__":
    main()
