#!/usr/bin/env python3
"""Compares `ceesafec build --emit c` with the pinned novac's C (docs/p5-plan.md).

novac emits with `--flat-c --no-closure-specialisation --no-placement --no-bce --no-oce`, the form P5 ports; ceesafec
is given the same switches. Every file of the two output directories must be byte-identical once the generated-by
banner's compiler name and version are made the same. Only the files novac builds are compared; the corpus's
`// profile:` and `// option:` lines are passed as in compare_parse.py.

usage: python3 tools/compare_c.py --ceesafec out/ceesafec --novac ~/.nova/0.6.0/bin/novac --root <Nova>
           [--extra=--split] [--extra=-g] [--list FILE] [--show N] paths...
"""
import argparse
import concurrent.futures
import difflib
import os
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from compare_parse import options_of  # noqa: E402
from compare_nir import files  # noqa: E402

SWITCHES = ["--flat-c", "--no-closure-specialisation", "--no-placement", "--no-bce", "--no-oce"]
BANNER = re.compile(rb"Generated by (novac \S+|ceesafec \S+)\. Do not edit\.")


def read_tree(directory):
    tree = {}
    for base, _, names in os.walk(directory):
        for name in names:
            full = os.path.join(base, name)
            with open(full, "rb") as f:
                tree[os.path.relpath(full, directory)] = BANNER.sub(b"Generated by COMPILER. Do not edit.", f.read())
    return tree


def compare(arguments):
    root, ceesafec, novac, path, extra = arguments
    options = options_of(root, path) + extra
    with tempfile.TemporaryDirectory() as out:
        reference_dir = os.path.join(out, "novac")
        ours_dir = os.path.join(out, "ceesafec")
        reference = subprocess.run([novac, "build", "--emit", "c", "-o", reference_dir] + SWITCHES + options + [path],
                                   cwd=root, capture_output=True)
        if reference.returncode != 0:
            return path, None, ""  # novac does not build it: nothing to compare
        ours = subprocess.run([ceesafec, "build", "--emit", "c", "-o", ours_dir] + SWITCHES + options + [path],
                              cwd=root, capture_output=True)
        if ours.returncode != 0:
            return path, False, "ceesafec failed: " + ours.stderr.decode("utf-8", "replace")[:2000]
        a, b = read_tree(reference_dir), read_tree(ours_dir)
        if a == b:
            return path, True, ""
        detail = []
        for name in sorted(set(a) | set(b)):
            if a.get(name) != b.get(name):
                if name not in a or name not in b:
                    detail.append(f"{name}: only in {'ceesafec' if name in b else 'novac'}")
                    continue
                diff = difflib.unified_diff(a[name].decode("utf-8", "replace").splitlines(),
                                            b[name].decode("utf-8", "replace").splitlines(), "novac/" + name,
                                            "ceesafec/" + name, n=1, lineterm="")
                detail.append("\n".join(list(diff)[:40]))
        return path, False, "\n".join(detail)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ceesafec", required=True)
    parser.add_argument("--novac", required=True)
    parser.add_argument("--root", required=True)
    parser.add_argument("--jobs", type=int, default=os.cpu_count())
    parser.add_argument("--list", help="write every differing file's path to FILE, sorted, one per line")
    parser.add_argument("--extra", action="append", default=[],
                        help="another switch for both compilers, e.g. --extra=--split or --extra=-g (repeatable)")
    parser.add_argument("--show", type=int, default=0, help="print the first lines of N differing files' diffs")
    parser.add_argument("--on", action="append", default=[],
                        choices=("closure-specialisation", "placement", "bce", "oce", "structured"),
                        help="leave this part on (its novac default) for both compilers (repeatable)")
    parser.add_argument("paths", nargs="+")
    args = parser.parse_args()
    off = {"closure-specialisation": "--no-closure-specialisation", "placement": "--no-placement", "bce": "--no-bce",
           "oce": "--no-oce", "structured": "--flat-c"}
    for part in args.on:
        if off[part] in SWITCHES:
            SWITCHES.remove(off[part])
    ceesafec = os.path.abspath(args.ceesafec)
    novac = os.path.expanduser(args.novac)
    work = [(args.root, ceesafec, novac, path, args.extra) for path in files(args.root, args.paths)]
    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        results = list(pool.map(compare, work))
    built = [(p, same, d) for p, same, d in results if same is not None]
    differ = sorted((p, d) for p, same, d in built if not same)
    if args.list:
        with open(args.list, "w", encoding="utf-8") as f:
            f.write("".join(p + "\n" for p, _ in differ))
    for p, d in differ[:args.show]:
        print(f"=== {p}\n{d}")
    print(f"compare_c: {len(results)} files, {len(built)} built by novac, {len(built) - len(differ)} identical, "
          f"{len(differ)} differ")
    return 1 if differ else 0


if __name__ == "__main__":
    sys.exit(main())
