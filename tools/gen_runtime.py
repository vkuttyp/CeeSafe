#!/usr/bin/env python3
"""Writes src/library/runtime.cee: the C runtime ceesafec embeds, from CeeSafe's runtime/ sources.

The runtime came from Nova v0.6.0 (the reference's CBackend: HostedRuntime, FloatRuntime, ThreadRuntime), renamed to
CeeSafe's names (Decision 0004); since Nova is no longer developed, runtime/ is the source of truth and is edited here.
Line endings are made "\\n". Each file is split into string literals of at most 4,000 bytes (C11 §5.2.4.1).

usage: python3 tools/gen_runtime.py   (formats with $CEESAFEC, default out/ceesafec)
"""

import os
import subprocess

from gen_library import literal

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

# (embedded name, source path under runtime/): the order the backend lists them in.
FILES = (
    ("ceesafe/rt.h", "include/ceesafe/rt.h"),
    ("ceesafe_rt_core.c", "core/ceesafe_rt_core.c"),
    ("ceesafe_rt_hosted.c", "hosted/ceesafe_rt_hosted.c"),
    ("ceesafe_rt_io.c", "hosted/ceesafe_rt_io.c"),
    ("ceesafe_rt_float.c", "hosted/ceesafe_rt_float.c"),
    ("ceesafe_rt_thread.c", "hosted/ceesafe_rt_thread.c"),
)


def main():
    files = []
    for name, path in FILES:
        with open(os.path.join(ROOT, "runtime", path), encoding="utf-8", newline="") as f:
            text = f.read()
        files.append((name, text.replace("\r\n", "\n").replace("\r", "\n")))
    chunks = []
    for k, (_, t) in enumerate(files):
        current, size = [], 0
        for ch in t:
            n = len(ch.encode("utf-8"))
            if size + n > 4000:
                chunks.append((k, "".join(current)))
                current, size = [], 0
            current.append(ch)
            size += n
        chunks.append((k, "".join(current)))
    counts = [sum(1 for f, _ in chunks if f == k) for k in range(len(files))]
    firsts, total = [], 0
    for n in counts:
        firsts.append(total)
        total += n
    names = "\n".join(f"    {k} => \"{n}\"," for k, (n, _) in enumerate(files[:-1]))
    count_arms = "\n".join(f"    {k} => {n}," for k, n in enumerate(counts[:-1]))
    first_arms = "\n".join(f"    {k} => {f}," for k, f in enumerate(firsts[:-1]))
    chunk_arms = "\n".join(f"    {j} => {literal(text)}," for j, (_, text) in enumerate(chunks[:-1]))
    source = f"""// The C runtime ceesafec embeds. GENERATED by tools/gen_runtime.py from runtime/: edit runtime/ and rerun it,
// do not edit this file. Each file is a run of chunks of at most 4,000 bytes,
// since C compilers need accept string literals of only 4,095 (C11 §5.2.4.1).

/// 0 rt.h, 1 the core, 2 hosted, 3 I/O, 4 the float formatter, 5 threads.
fn runtimeFileName(k: usize) -> StringView => match (k) {{
{names}
    _ => "{files[-1][0]}",
}};

fn runtimeChunkCount(k: usize) -> usize => match (k) {{
{count_arms}
    _ => {counts[-1]},
}};

fn runtimeFirstChunk(k: usize) -> usize => match (k) {{
{first_arms}
    _ => {firsts[-1]},
}};

fn runtimeChunk(j: usize) -> StringView => match (j) {{
{chunk_arms}
    _ => {literal(chunks[-1][1])},
}};

/// Appends the whole text of runtime file `k`.
fn appendRuntimeText(out: borrow mut Vector<u8>, k: usize) -> Result<void, AllocError> {{
    for (j in 0..runtimeChunkCount(k)) {{
        appendText(out, runtimeChunk(runtimeFirstChunk(k) + j))?;
    }}
    return Ok();
}}
"""
    path = os.path.join(ROOT, "src", "library", "runtime.cee")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    formatter = os.environ.get("CEESAFEC", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "out", "ceesafec"))
    subprocess.run([formatter, "fmt", path], check=True)
    print(f"gen_runtime: wrote {path} ({len(files)} files from runtime/)")


if __name__ == "__main__":
    main()
