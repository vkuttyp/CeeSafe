#!/usr/bin/env python3
"""Writes src/library/runtime.cee: the C runtime novac embeds (the reference's CBackend: HostedRuntime, FloatRuntime,
ThreadRuntime; Nova.Compiler.csproj's embedded resources).

The files are read with `git show TAG:PATH` from a Nova repository, so its working tree may be anywhere; line endings
are made "\\n" as ReadResource does. Each file is split into string literals of at most 4,000 bytes (C11 §5.2.4.1).

usage: python3 tools/gen_runtime.py [--nova PATH] [--tag TAG]   (default ~/Nova, v0.6.0; formats with $CEESAFEC, default out/ceesafec)
"""

import argparse
import os
import subprocess

from gen_library import literal

# (output path, source path): the order CBackend lists them in.
FILES = (
    ("nova/rt.h", "runtime/include/nova/rt.h"),
    ("nova_rt_core.c", "runtime/core/nova_rt_core.c"),
    ("nova_rt_hosted.c", "runtime/hosted/nova_rt_hosted.c"),
    ("nova_rt_io.c", "runtime/hosted/nova_rt_io.c"),
    ("nova_rt_float.c", "runtime/hosted/nova_rt_float.c"),
    ("nova_rt_thread.c", "runtime/hosted/nova_rt_thread.c"),
)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--nova", default=os.path.expanduser("~/Nova"))
    parser.add_argument("--tag", default="v0.6.0")
    args = parser.parse_args()
    files = []
    for name, path in FILES:
        text = subprocess.run(["git", "-C", args.nova, "show", f"{args.tag}:{path}"], capture_output=True,
                              check=True).stdout.decode("utf-8")
        if text.startswith("﻿"):
            text = text[1:]
        files.append((name, text.replace("\r\n", "\n").replace("\r", "\n")))
    chunks = []
    for k, (_, t) in enumerate(files):
        current, size = [], 0
        for ch in t:
            n = len(ch.encode("utf-8"))
            if size + n > 4000:
                chunks.append((k, "".join(current)))
                current, size = [], 0
            current.append(ch)
            size += n
        chunks.append((k, "".join(current)))
    counts = [sum(1 for f, _ in chunks if f == k) for k in range(len(files))]
    firsts, total = [], 0
    for n in counts:
        firsts.append(total)
        total += n
    names = "\n".join(f"    {k} => \"{n}\"," for k, (n, _) in enumerate(files[:-1]))
    count_arms = "\n".join(f"    {k} => {n}," for k, n in enumerate(counts[:-1]))
    first_arms = "\n".join(f"    {k} => {f}," for k, f in enumerate(firsts[:-1]))
    chunk_arms = "\n".join(f"    {j} => {literal(text)}," for j, (_, text) in enumerate(chunks[:-1]))
    source = f"""// The C runtime novac embeds (the reference's CBackend.HostedRuntime, FloatRuntime and ThreadRuntime). GENERATED by
// tools/gen_runtime.py from Nova {args.tag}: rerun it, do not edit. Each file is a run of chunks of at most 4,000 bytes,
// since C compilers need accept string literals of only 4,095 (C11 §5.2.4.1).

/// 0 rt.h, 1 the core, 2 hosted, 3 I/O, 4 the float formatter, 5 threads.
fn runtimeFileName(k: usize) -> StringView => match (k) {{
{names}
    _ => "{files[-1][0]}",
}};

fn runtimeChunkCount(k: usize) -> usize => match (k) {{
{count_arms}
    _ => {counts[-1]},
}};

fn runtimeFirstChunk(k: usize) -> usize => match (k) {{
{first_arms}
    _ => {firsts[-1]},
}};

fn runtimeChunk(j: usize) -> StringView => match (j) {{
{chunk_arms}
    _ => {literal(chunks[-1][1])},
}};

/// Appends the whole text of runtime file `k`.
fn appendRuntimeText(out: borrow mut Vector<u8>, k: usize) -> Result<void, AllocError> {{
    for (j in 0..runtimeChunkCount(k)) {{
        appendText(out, runtimeChunk(runtimeFirstChunk(k) + j))?;
    }}
    return Ok();
}}
"""
    path = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "src", "library", "runtime.cee"))
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    formatter = os.environ.get("CEESAFEC", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "out", "ceesafec"))
    subprocess.run([formatter, "fmt", path], check=True)
    print(f"gen_runtime: wrote {path} ({len(files)} files from Nova {args.tag})")


if __name__ == "__main__":
    main()
