#!/usr/bin/env python3
"""Writes tests/support/run-pass/dotnet-double.nova from .NET's double.ToString("R") (docs/p3-plan.md, S0).

Bit patterns: special values; powers of ten and of two across the range; values at the edges of .NET's switch to
scientific notation; seeded random doubles; and f32 values widened to f64, as f32 constants reach the HIR dump. The
oracle (tools/oracles/double-format) formats each; the test prints the same patterns with appendDotNetDouble.

usage: python3 tools/oracles/gen_double_cases.py ORACLE_BINARY   (then review the diff)
"""

import os
import random
import struct
import subprocess
import sys


def bits(v):
    return struct.unpack("<Q", struct.pack("<d", v))[0]


def patterns():
    out = [0, 1 << 63, 0x7FF0000000000000, 0xFFF0000000000000, 0x7FF8000000000000, 1, 0x000FFFFFFFFFFFFF,
           0x0010000000000000, 0x7FEFFFFFFFFFFFFF, bits(2.0 ** -25), bits(-2.0 ** -25), bits(2.0 ** -958),
           bits(-2.0 ** -958)]
    for k in range(-20, 24):
        for m in (1.0, 1.5, 9.99, 1.2345678901234567):
            out += [bits(m * 10.0 ** k), bits(-m * 10.0 ** k)]
    for k in range(-1074, 1024, 37):
        out.append(bits(2.0 ** k))
    rng = random.Random(20261030)
    for _ in range(200):
        out.append(rng.getrandbits(64) & ~(0x7FF << 52) | (rng.randrange(1, 2047) << 52))
    for _ in range(100):
        f = struct.unpack("<f", struct.pack("<I", rng.getrandbits(32) & 0x7F7FFFFF))[0]
        out.append(bits(f))
    for v in (0.1, 0.2, 0.3, 1 / 3, 2 / 3, 3.14159, 2.718281828459045, 1e100, 1e-100, 123.456, 0.1 + 0.2):
        out.append(bits(v))
    return out


BODY = r'''
fn main() {
    for (b in BITS) {
        var line = Vector<u8>.create();
        appendDotNetDouble(mut line, f64.fromBits(b))!;
        line.push('\n')!;
        Console.writeBytes(line.view());
    }
}
'''


def main():
    oracle = sys.argv[1]
    ps = patterns()
    out = subprocess.run([oracle], input="".join(f"{p:016X}\n" for p in ps), capture_output=True, text=True,
                         check=True).stdout.rstrip("\n").split("\n")
    assert len(out) == len(ps)
    expect = "\n".join(f"// expect-stdout: {line}" for line in out)
    array = ",\n".join(f"    0x{p:016X}" for p in ps)
    source = ("// src/support/dotnet_double.nova against .NET's double.ToString(\"R\"). GENERATED by\n"
              "// tools/oracles/gen_double_cases.py from tools/oracles/double-format: edit the generator.\n" + expect +
              f"\n\nconst BITS: [u64; {len(ps)}] = [\n{array},\n];\n" + BODY)
    path = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "..", "tests", "support", "run-pass",
                                         "dotnet-double.nova"))
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    print(f"wrote {path} ({len(ps)} patterns)")


if __name__ == "__main__":
    main()
