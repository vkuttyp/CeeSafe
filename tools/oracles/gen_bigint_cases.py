#!/usr/bin/env python3
"""Writes tests/support/run-pass/bigint-cases.nova from Python's arbitrary-precision integers.

The oracle is Python's int, which is independent of src/support/bigint.nova. Semantics follow the reference's
System.Numerics.BigInteger as used by IntegerSemantics.cs: truncating division (the quotient rounds toward zero, the
remainder has the dividend's sign), Wrap (reduce modulo 2^bits, then read as signed or unsigned) and NovaType.Fits.

usage: python3 tools/oracles/gen_bigint_cases.py   (rewrites the test and formats it with $NOVAC, default the pinned
       ~/.nova/bin/novac; review the diff)
"""

import os
import random
import subprocess

EDGES = [
    0, 1, -1, 7, -10, 2**31 - 1, -2**31, 2**32, 2**63 - 1, -2**63, 2**64 - 1, -(2**64 - 1), 2**64, 2**127,
    -(2**128) + 1, 10**40 + 7, -(3**60),
]


def trunc_divrem(a, b):
    q = abs(a) // abs(b)
    if (a < 0) != (b < 0):
        q = -q
    return q, a - q * b


def cmp(a, b):
    return (a > b) - (a < b)


def wrap(v, bits, signed):
    r = v % (1 << bits)
    if signed and r >= 1 << (bits - 1):
        r -= 1 << bits
    return r


def fits(v, bits, signed):
    lo, hi = (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if signed else (0, (1 << bits) - 1)
    return lo <= v <= hi


def pair_line(a, b):
    parts = [f"{a} {b}:", f"sum {a + b}", f"difference {a - b}", f"product {a * b}", f"compare {cmp(a, b)}"]
    if b != 0:
        q, r = trunc_divrem(a, b)
        parts += [f"quotient {q}", f"remainder {r}"]
    return " ".join(parts)


def wrap_line(v):
    parts = [f"{v}:"]
    for bits in (8, 16, 32, 64):
        for signed in (True, False):
            name = ("i" if signed else "u") + str(bits)
            parts.append(f"{name} {wrap(v, bits, signed)}{'' if fits(v, bits, signed) else '!'}")
    return " ".join(parts)


def main():
    rng = random.Random(2026)
    randoms = []
    for _ in range(40):
        a = rng.getrandbits(rng.randint(1, 400)) * rng.choice((1, -1))
        b = rng.getrandbits(rng.randint(1, 200)) * rng.choice((1, -1))
        randoms.append((a, b))
    pairs = [(a, b) for a in EDGES for b in EDGES] + randoms
    values = sorted({v for p in pairs for v in p}, key=lambda v: (abs(v), v))
    index = {v: i for i, v in enumerate(values)}

    expect = [f"// expect-stdout: {pair_line(a, b)}" for a, b in pairs]
    expect += [f"// expect-stdout: wrap {wrap_line(v)}" for v in EDGES]
    expect.append(f"// expect-stdout: power10 50 / 3^40: {trunc_divrem(10**50, 3**40)[0]} rest {10**50 % 3**40}")
    expect.append(f"// expect-stdout: hex ffffffffffffffffffffffffffffffff = {int('f' * 32, 16)}, hex bad = null")

    value_arms = "\n".join(f"    {i} => \"{v}\"," for i, v in enumerate(values[:-1]))
    pair_arms = "\n".join(f"    {n} => {index[a] * 1000 + index[b]}," for n, (a, b) in enumerate(pairs[:-1]))
    last = pairs[-1]
    edge_arms = "\n".join(f"    {i} => {index[v]}," for i, v in enumerate(EDGES[:-1]))

    source = f"""// src/support/bigint.nova against Python's integers. GENERATED by tools/oracles/gen_bigint_cases.py: edit the generator,
// not this file. Each pair line has sum, difference, product, comparison and (for a non-zero divisor) truncating
// quotient and remainder; each wrap line has the value wrapped to each integer type, with `!` where it does not fit.
{chr(10).join(expect)}

fn text(i: usize) -> StringView => match (i) {{
{value_arms}
    _ => "{values[-1]}",
}};

// Pair n is values a * 1000 + b.
fn pair(n: usize) -> usize => match (n) {{
{pair_arms}
    _ => {index[last[0]] * 1000 + index[last[1]]},
}};

fn edge(i: usize) -> usize => match (i) {{
{edge_arms}
    _ => {index[EDGES[-1]]},
}};

fn parseInt(t: StringView) -> BigInt {{
    let negative = t.length > 0 && t[0] == '-';
    let digits = if (negative) t[1..] else t;
    return BigInt.of(negative, BigNat.parse(digits.bytes(), 10)!!);
}}

fn write(n: borrow BigInt) {{
    var out = Vector<u8>.create();
    n.appendDecimal(mut out)!;
    Console.writeBytes(out.view());
}}

fn writeNat(n: borrow BigNat) {{
    var out = Vector<u8>.create();
    n.appendDecimal(mut out)!;
    Console.writeBytes(out.view());
}}

fn main() {{
    for (n in 0..{len(pairs)}usize) {{
        let a = parseInt(text(pair(n) / 1000));
        let b = parseInt(text(pair(n) % 1000));
        write(a);
        Console.write(" ");
        write(b);
        Console.write(": sum ");
        write(BigInt.add(a, b)!);
        Console.write(" difference ");
        write(BigInt.sub(a, b)!);
        Console.write(" product ");
        write(BigInt.mul(a, b)!);
        Console.write(" compare ");
        Console.write(a.compare(b));
        if (!b.isZero()) {{
            let d = BigInt.divRem(a, b)!;
            Console.write(" quotient ");
            write(d.quotient);
            Console.write(" remainder ");
            write(d.remainder);
        }}
        Console.writeLine("");
    }}
    for (i in 0..{len(EDGES)}usize) {{
        let v = parseInt(text(edge(i)));
        Console.write("wrap ");
        write(v);
        Console.write(":");
        for (k in 0..8usize) {{
            let bits: usize = match (k / 2) {{
                0 => 8,
                1 => 16,
                2 => 32,
                _ => 64,
            }};
            let signed = k % 2 == 0;
            Console.write(if (signed) " i" else " u");
            Console.write(bits);
            Console.write(" ");
            write(BigInt.wrap(v, bits, signed)!);
            if (!v.fits(bits, signed)) {{
                Console.write("!");
            }}
        }}
        Console.writeLine("");
    }}
    let p = BigNat.power10(50)!;
    var three = BigNat.fromU64(1)!;
    for (i in 0..40) {{
        three = BigNat.mulSmall(three, 3)!;
    }}
    let d = BigNat.divRem(p, three)!;
    Console.write("power10 50 / 3^40: ");
    writeNat(d.quotient);
    Console.write(" rest ");
    writeNat(d.remainder);
    Console.writeLine("");
    let hex = BigNat.parse("ffffffffffffffffffffffffffffffff".bytes(), 16)!!;
    Console.write("hex ffffffffffffffffffffffffffffffff = ");
    writeNat(hex);
    Console.write(", hex bad = ");
    Console.writeLine(if (BigNat.parse("12g".bytes(), 16)! == null) "null" else "parsed");
}}
"""
    path = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "..", "tests", "support", "run-pass",
                                         "bigint-cases.nova"))
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    novac = os.environ.get("NOVAC", os.path.expanduser("~/.nova/bin/novac"))
    subprocess.run([novac, "fmt", path], check=True)
    print(f"wrote {path} ({len(pairs)} pairs, {len(EDGES)} wrap values)")


if __name__ == "__main__":
    main()
