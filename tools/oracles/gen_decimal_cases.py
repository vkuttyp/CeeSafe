#!/usr/bin/env python3
"""Writes tests/support/run-pass/decimal-float.nova from .NET's double.Parse and float.Parse (docs/p3-plan.md, S1b).

Inputs: halfway cases between neighbouring doubles and floats, subnormals, the largest finite values and just past
them, long digit strings, and seeded random decimals. The oracle (tools/oracles/decimal-parse) gives each result's
bits; the test parses the same text with parseDecimalFloat and prints the bits.

usage: python3 tools/oracles/gen_decimal_cases.py ORACLE_BINARY
"""

import decimal
import os
import random
import struct
import subprocess
import sys

decimal.getcontext().prec = 1200


def exact(v):
    return format(decimal.Decimal(v), "f")


def cases():
    out = []
    fixed = ["0.0", "1.0", "1.5", "0.1", "0.2", "0.3", "3.14159", "2.718281828459045", "1e308", "1.7976931348623157e308",
             "1.7976931348623158e308", "1.7976931348623159e308", "2e308", "4.9e-324", "5e-324", "2.4703282292062327e-324",
             "2.4703282292062328e-324", "1e-400", "2.2250738585072014e-308", "2.2250738585072011e-308", "123456789012345678901234567890.5",
             "0.000001", "9007199254740993.0", "9007199254740995.0", "3.4028234663852886e38", "3.4028235e38",
             "3.4028236e38", "3.40282357e38", "1.401298464324817e-45", "7.0e-46", "7.1e-46", "1.17549435e-38",
             "16777217.0", "16777219.0", "0.1e1", "100e-2", "1.0e0", "1e22", "1e23", "8.98846567431158e307"]
    for t in fixed:
        out += [("64", t), ("32", t)]
    rng = random.Random(20261030)
    # Halfway points between neighbouring doubles and floats, and just around them.
    for _ in range(150):
        b = rng.getrandbits(64) & 0x7FEFFFFFFFFFFFFF
        a = struct.unpack("<d", struct.pack("<Q", b))[0]
        c = struct.unpack("<d", struct.pack("<Q", b + 1))[0]
        mid = (decimal.Decimal(a) + decimal.Decimal(c)) / 2
        out.append(("64", format(mid, "e")))
    for _ in range(150):
        b = rng.getrandbits(32) & 0x7F7FFFFF
        a = struct.unpack("<f", struct.pack("<I", b))[0]
        c = struct.unpack("<f", struct.pack("<I", b + 1))[0]
        mid = (decimal.Decimal(a) + decimal.Decimal(c)) / 2
        out.append(("32", format(mid, "e")))
    for _ in range(300):
        digits = "".join(rng.choice("0123456789") for _ in range(rng.randint(1, 25)))
        point = rng.randint(0, len(digits))
        text = (digits[:point] or "0") + "." + (digits[point:] or "0") + f"e{rng.randint(-340, 320)}"
        out.append((rng.choice(["64", "32"]), text))
    return out


BODY = r'''
fn main() {
    for (k in 0..COUNT) {
        let format = if (WIDTH[k] == 32) f32Format() else f64Format();
        let value = parseDecimalFloat(text(k).bytes(), format)!;
        var line = Vector<u8>.create();
        appendHex(mut line, value.bits(), 16)!;
        line.push('\n')!;
        Console.writeBytes(line.view());
    }
}
'''


def main():
    oracle = sys.argv[1]
    cs = cases()
    out = subprocess.run([oracle], input="".join(f"{w} {t}\n" for w, t in cs), capture_output=True, text=True,
                         check=True).stdout.rstrip("\n").split("\n")
    assert len(out) == len(cs)
    expect = "\n".join(f"// expect-stdout: {line}" for line in out)
    widths = ", ".join(w for w, _ in cs)
    arms = "\n".join(f'    {k} => "{t}",' for k, (_, t) in enumerate(cs[:-1]))
    source = ("// src/support/decimal_float.nova against .NET's double.Parse and float.Parse. GENERATED by\n"
              "// tools/oracles/gen_decimal_cases.py from tools/oracles/decimal-parse: edit the generator.\n" + expect +
              f"\n\nconst COUNT: usize = {len(cs)};\n\nconst WIDTH: [u32; {len(cs)}] = [{widths}];\n\n"
              f"fn text(k: usize) -> StringView => match (k) {{\n{arms}\n    _ => \"{cs[-1][1]}\",\n}};\n" + BODY)
    path = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "..", "tests", "support", "run-pass",
                                         "decimal-float.nova"))
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    print(f"wrote {path} ({len(cs)} cases)")


if __name__ == "__main__":
    main()
