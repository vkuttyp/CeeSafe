#!/usr/bin/env python3
"""Writes src/support/json_escapes.nova from tools/oracles/data/json-escaped-bmp.txt.

The data file lists the BMP code points .NET's JavaScriptEncoder.UnsafeRelaxedJsonEscaping escapes (the encoder of
Nova's DiagnosticJson); tools/oracles/JsonEscapes.cs extracts it from a .NET install. The generated table is a
constant array of inclusive ranges searched by `jsonEscapesBmp`.

usage: python3 tools/oracles/gen_json_escapes.py   (formats the output with $NOVAC, default ~/.nova/0.5.0/bin/novac)
"""

import os
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))


def main():
    ranges = []
    with open(os.path.join(ROOT, "tools", "oracles", "data", "json-escaped-bmp.txt"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                continue
            lo, hi = line.split()
            ranges.append((int(lo, 16), int(hi, 16)))
    flat = [v for r in ranges for v in r]
    values = ", ".join(f"0x{v:04X}u16" if i == 0 else f"0x{v:04X}" for i, v in enumerate(flat))
    source = f"""// GENERATED by tools/oracles/gen_json_escapes.py from tools/oracles/data/json-escaped-bmp.txt: edit those, not this file.
// Source: .NET 10.0.12's JavaScriptEncoder.UnsafeRelaxedJsonEscaping, the encoder of Nova's DiagnosticJson.
// The BMP code points written as \\uXXXX by Nova's JSON output: {len(ranges)} inclusive ranges, sorted, as (low, high) pairs.
const JSON_ESCAPED_RANGES: [u16; {len(flat)}] = [{values}];

/// Whether .NET's relaxed JSON encoder escapes the BMP code point `c` (binary search over the ranges).
fn jsonEscapesBmp(c: u32) -> bool {{
    let table = JSON_ESCAPED_RANGES;
    var lo: usize = 0;
    var hi: usize = table.length / 2;
    while (lo < hi) {{
        let mid = lo + (hi - lo) / 2;
        if (c < table[2 * mid] as u32) {{
            hi = mid;
        }} else if (c > table[2 * mid + 1] as u32) {{
            lo = mid + 1;
        }} else {{
            return true;
        }}
    }}
    return false;
}}
"""
    path = os.path.join(ROOT, "src", "support", "json_escapes.nova")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    novac = os.environ.get("NOVAC", os.path.expanduser("~/.nova/0.5.0/bin/novac"))
    subprocess.run([novac, "fmt", path], check=True)
    print(f"wrote {path} ({len(ranges)} ranges)")


if __name__ == "__main__":
    main()
