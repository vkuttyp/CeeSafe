#!/usr/bin/env python3
"""Writes tests/support/run-pass/source-positions.nova from an independent Python model of Nova's SourceText.

The model is the reference's behaviour: File.ReadAllText drops a leading UTF-8 BOM, SourceText drops one more,
ill-formed UTF-8 decodes to U+FFFD per maximal subpart (Python's "replace" handler does the same; both were checked
against novac 0.3.1's columns, docs/p1-probes.md §6), lines start after "\\r\\n", "\\r" or "\\n", and positions are
1-based with columns in UTF-16 code units. For every ASCII byte offset of each input (an ASCII byte always starts a
sequence) and the end, the test prints line, column and UTF-16 offset; the expected lines come from this model.

usage: python3 tools/oracles/gen_source_positions.py   (rewrites the test and formats it with $NOVAC, default the
       pinned ~/.nova/0.5.0/bin/novac; review the diff)
"""

import os
import subprocess

BOM = b"\xef\xbb\xbf"

CASES = [
    b"",
    b"fn main() {}\n",
    BOM + b"a\nb",
    BOM + BOM + b"x\r\ny",
    b"a\r\nb\rc\nd\r\r\n\ne",
    "é = 1; € + 😀 x".encode(),
    b"/* \x80 */ z\n\xe2\x82 y \xf0\x9f\x98 w",
    b"\xc0\xaf a \xed\xa0\x80 b \xf4\x90\x80\x80 c \xff\xfe d",
    b"\xc3\x28\xe2\x82\x80\xf0\x9f\x98a\xe0\x80\x80!",
    b"line\n\xef\xbb\xbfmid-bom\n",
    "\U0001F600\U0001F600\r\n\U0001F600!".encode(),
]


def strip_boms(raw):
    for _ in range(2):
        if raw.startswith(BOM):
            raw = raw[3:]
    return raw


def utf16_units(data):
    return len(data.decode("utf-8", "replace").encode("utf-16-le")) // 2


def model(raw):
    text = strip_boms(raw)
    units = text.decode("utf-8", "replace").encode("utf-16-le")
    chars = [int.from_bytes(units[i:i + 2], "little") for i in range(0, len(units), 2)]
    starts = [0]
    i = 0
    while i < len(chars):
        if chars[i] == 0x0D:
            if i + 1 < len(chars) and chars[i + 1] == 0x0A:
                i += 1
            starts.append(i + 1)
        elif chars[i] == 0x0A:
            starts.append(i + 1)
        i += 1
    out = []
    for k in range(len(text) + 1):
        if k < len(text) and text[k] >= 0x80:
            continue
        u = utf16_units(text[:k])
        line = max(j for j, s in enumerate(starts) if s <= u)
        out.append(f"{k}={line + 1}:{u - starts[line] + 1}/{u}")
    return len(starts), out


def nova_call(n, raw):
    """A call of show; an array temporary cannot be sliced (N0247), so it is bound to a local first."""
    if not raw:
        return [f"    show({n}, Vector<u8>.create());"]
    array = ", ".join(f"0x{b:02X}u8" if i == 0 else f"0x{b:02X}" for i, b in enumerate(raw))
    return [f"    let bytes{n} = [{array}];", f"    show({n}, bytesOf(bytes{n}[..]));"]


def main():
    expect, calls = [], []
    for n, raw in enumerate(CASES):
        lines, positions = model(raw)
        expect.append(f"// expect-stdout: case {n}: {lines} lines | {' '.join(positions)}")
        calls += nova_call(n, raw)
    source = "\n".join([
        "// src/support/source.nova against an independent Python model of Nova's SourceText. GENERATED by",
        "// tools/oracles/gen_source_positions.py: edit the generator, not this file. For each input, the line count and,",
        "// for every ASCII byte offset and the end, `offset=line:column/utf16-offset` (ROADMAP §3.2).",
        *expect,
        "",
        "fn bytesOf(bytes: Slice<u8>) -> Vector<u8> => copyBytes(bytes)!;",
        "",
        "fn show(n: u32, raw: Vector<u8>) {",
        "    let source = SourceText.create(\"case.nova\".bytes(), raw.view())!;",
        "    Console.write(\"case \");",
        "    Console.write(n);",
        "    Console.write(\": \");",
        "    Console.write(source.lineCount());",
        "    Console.write(\" lines |\");",
        "    for (k in 0..(source.text.length + 1)) {",
        "        if (k < source.text.length && source.text[k] >= 0x80) {",
        "            continue;",
        "        }",
        "        let p = source.position(k);",
        "        Console.write(\" \");",
        "        Console.write(k);",
        "        Console.write(\"=\");",
        "        Console.write(p.line);",
        "        Console.write(\":\");",
        "        Console.write(p.column);",
        "        Console.write(\"/\");",
        "        Console.write(source.utf16Offset(k));",
        "    }",
        "    Console.writeLine(\"\");",
        "}",
        "",
        "fn main() {",
        *calls,
        "}",
        "",
    ])
    path = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "support", "run-pass", "source-positions.nova")
    with open(os.path.normpath(path), "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    novac = os.environ.get("NOVAC", os.path.expanduser("~/.nova/0.5.0/bin/novac"))
    subprocess.run([novac, "fmt", os.path.normpath(path)], check=True)
    print(f"wrote {os.path.normpath(path)} ({len(CASES)} cases)")


if __name__ == "__main__":
    main()
