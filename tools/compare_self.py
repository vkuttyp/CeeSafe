#!/usr/bin/env python3
"""Compares ceesafec's C for CeeSafe itself with novac's (docs/p7-plan.md).

novac cannot read CeeSafe's names (Decision 0003), so it gets a copy of the tree at a commit (`git archive`) renamed
to Nova's: `ceesafe.toml` → `nova.toml`, `src/**/*.cee` → `.nova`. ceesafec builds the same commit with its own names.
Both emit C (`build --emit c`) with the parts given by --on left on and the rest off, and with --report also print
that report; the C must be identical once the `src/` file names are mapped back, and so must the report.

usage: python3 tools/compare_self.py --ceesafec out/ceesafec --novac ~/.nova/0.6.0/bin/novac [--commit HEAD]
           [--on PART]... [--report NAME] [--extra=--split]...
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from names import map_back, nova_names_in  # noqa: E402

OFF = {"closure-specialisation": "--no-closure-specialisation", "placement": "--no-placement", "bce": "--no-bce",
       "oce": "--no-oce", "structured": "--flat-c"}
REPORTS = {"closure-calls": "--explain-closure-calls", "allocations": "--explain-allocations",
           "bounds-checks": "--explain-bounds-checks", "overflow-checks": "--explain-overflow-checks"}
NEWLINE = b"\n"
SRC_NAME = re.compile(rb'(src/[A-Za-z0-9_/.-]*)\.nova\b')


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ceesafec", required=True)
    parser.add_argument("--novac", required=True)
    parser.add_argument("--repo", default=os.path.normpath(os.path.join(os.path.dirname(__file__), "..")))
    parser.add_argument("--commit", default="WORKTREE", help="a commit, or WORKTREE for the working tree (default)")
    parser.add_argument("--on", action="append", default=[], choices=sorted(OFF))
    parser.add_argument("--report", choices=sorted(REPORTS))
    parser.add_argument("--extra", action="append", default=[])
    args = parser.parse_args()
    switches = [OFF[p] for p in sorted(OFF) if p not in args.on] + args.extra
    if args.report:
        switches.append(REPORTS[args.report])
    with tempfile.TemporaryDirectory() as work:
        ours, theirs = os.path.join(work, "cee"), os.path.join(work, "nova")
        if args.commit == "WORKTREE":
            archive = subprocess.run(["tar", "-c", "-C", args.repo, "ceesafe.toml", "src"], capture_output=True,
                                     check=True, env=dict(os.environ, COPYFILE_DISABLE="1")).stdout
        else:
            archive = subprocess.run(["git", "-C", args.repo, "archive", args.commit, "ceesafe.toml", "src"],
                                     capture_output=True, check=True).stdout
        for directory in (ours, theirs):
            os.makedirs(directory)
            subprocess.run(["tar", "-x", "-C", directory], input=archive, check=True)
        os.rename(os.path.join(theirs, "ceesafe.toml"), os.path.join(theirs, "nova.toml"))
        for base, _, names in os.walk(os.path.join(theirs, "src")):
            for name in names:
                if name.endswith(".cee"):
                    os.rename(os.path.join(base, name), os.path.join(base, name[:-4] + ".nova"))
        results, leftovers = [], []
        for compiler, directory in ((os.path.expanduser(args.novac), theirs), (os.path.abspath(args.ceesafec), ours)):
            p = subprocess.run([compiler, "build", "--emit", "c", "-o", "c"] + switches, cwd=directory,
                               capture_output=True)
            if p.returncode != 0:
                sys.exit(f"compare_self: {compiler} failed:\n{p.stderr.decode()[:2000]}")
            tree = {}
            for base, _, names in os.walk(os.path.join(directory, "c")):
                for name in names:
                    with open(os.path.join(base, name), "rb") as f:
                        text = f.read()
                    relative = os.path.relpath(os.path.join(base, name), os.path.join(directory, "c"))
                    if directory == ours:
                        leftovers += [f"{relative}: {line}" for line in nova_names_in(text)]
                    # Both mapped back: CeeSafe's sources hold CeeSafe's names in string literals, which both copy.
                    tree[map_back(relative)] = map_back(
                        SRC_NAME.sub(rb"\1.cee", re.sub(rb"Generated by \S+ \S+\.", b"Generated by.", text)))
            results.append((tree, map_back(SRC_NAME.sub(rb"\1.cee", p.stdout))))
        if leftovers:
            print("compare_self: Nova C names left in ceesafec's C:\n" + "\n".join(leftovers[:20]))
            return 1
        (reference, reference_report), (actual, actual_report) = results
        differ = sorted(name for name in set(reference) | set(actual) if reference.get(name) != actual.get(name))
        lines = sum(text.count(b"\n") for text in actual.values())
        print(f"compare_self ({', '.join(args.on) or 'all off'}{', ' + ' '.join(args.extra) if args.extra else ''}): "
              f"{len(actual)} files, {lines} lines; "
              f"{'identical' if not differ else 'DIFFER: ' + ', '.join(differ)}"
              + (f"; report {'identical' if reference_report == actual_report else 'DIFFERS'}"
                 f" ({reference_report.count(NEWLINE)} lines)" if args.report else ""))
        return 1 if differ or (args.report and reference_report != actual_report) else 0


if __name__ == "__main__":
    sys.exit(main())
