#!/usr/bin/env python3
"""Writes src/diagnostics/catalog.cee: each diagnostic code's one-line meaning, the JSON format's "summary".

It replicates the reference's DiagnosticCatalog.Load (Documentation/EmbeddedDocs.cs) over CeeSafe's specification
(Decision 0006): rows `| N0123 | meaning | ... |` of spec/diagnostics.md first, then of the other documents of spec/
in ordinal path order (spec/*.md, spec/api/*.md, spec/decisions/*.md); the first row for a code wins.

usage: python3 tools/gen_catalog.py   (formats with $CEESAFEC, default out/ceesafec; review the diff)
"""

import argparse
import glob
import os
import re
import subprocess

CODE = re.compile(r"^N\d{4}$")
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))


def embedded():
    paths = []
    for pattern in ("spec/*.md", "spec/api/*.md", "spec/decisions/*.md"):
        paths += [os.path.relpath(p, ROOT).replace(os.sep, "/") for p in glob.glob(os.path.join(ROOT, pattern))]
    rest = sorted(p for p in set(paths) if p != "spec/diagnostics.md")
    return ["spec/diagnostics.md"] + rest


def entries():
    found = {}
    for path in embedded():
        with open(os.path.join(ROOT, path), encoding="utf-8") as f:
            text = f.read().replace("\r\n", "\n").replace("\r", "\n")
        for line in text.split("\n"):
            cells = line.split("|")
            if len(cells) < 4 or not line.startswith("|"):
                continue
            code = cells[1].strip().strip("`")
            if not CODE.match(code) or code in found:
                continue
            found[code] = cells[2].strip()
    return found


def literal(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.parse_args()
    found = entries()
    arms = "\n".join(f"    {int(code[1:])} => {literal(meaning)}," for code, meaning in sorted(found.items()))
    source = f"""// Each diagnostic code's meaning, as the reference's DiagnosticCatalog finds it in its embedded documents (the JSON
// "summary", tooling.md §5.1). GENERATED by tools/gen_catalog.py from CeeSafe's spec/: rerun it, do not edit.

/// The meaning of code N`number`, or "" for a code no document lists.
fn summaryOf(number: u32) -> StringView => match (number) {{
{arms}
    _ => "",
}};
"""
    path = os.path.join(ROOT, "src", "diagnostics", "catalog.cee")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    formatter = os.environ.get("CEESAFEC", os.path.join(ROOT, "out", "ceesafec"))
    subprocess.run([formatter, "fmt", path], check=True)
    print(f"gen_catalog: wrote {path} ({len(found)} codes from spec/)")


if __name__ == "__main__":
    main()
