#!/usr/bin/env python3
"""Writes src/diagnostics/catalog.nova: each diagnostic code's one-line meaning, the JSON format's "summary".

It replicates the reference's DiagnosticCatalog.Load (Documentation/EmbeddedDocs.cs): rows `| N0123 | meaning | ... |`
of docs/diagnostics.md first, then of the other embedded documents under docs/ in ordinal path order (docs/*.md,
docs/api/*.md, docs/decisions/*.md, docs/cosmoos/profiles.md); the first row for a code wins. The documents are read
from a Nova checkout at the pinned tag, which must be clean.

usage: python3 tools/gen_catalog.py [--nova PATH]   (default ~/Nova; formats with $NOVAC, default the pinned
       ~/.nova/0.5.0/bin/novac; review the diff)
"""

import argparse
import glob
import os
import re
import subprocess
import sys

CODE = re.compile(r"^N\d{4}$")


def embedded(nova):
    paths = []
    for pattern in ("docs/*.md", "docs/api/*.md", "docs/decisions/*.md", "docs/cosmoos/profiles.md"):
        paths += [os.path.relpath(p, nova).replace(os.sep, "/") for p in glob.glob(os.path.join(nova, pattern))]
    rest = sorted(p for p in set(paths) if p != "docs/diagnostics.md")
    return ["docs/diagnostics.md"] + rest


def entries(nova):
    found = {}
    for path in embedded(nova):
        with open(os.path.join(nova, path), encoding="utf-8") as f:
            text = f.read().replace("\r\n", "\n").replace("\r", "\n")
        for line in text.split("\n"):
            cells = line.split("|")
            if len(cells) < 4 or not line.startswith("|"):
                continue
            code = cells[1].strip().strip("`")
            if not CODE.match(code) or code in found:
                continue
            found[code] = cells[2].strip()
    return found


def literal(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--nova", default=os.path.expanduser("~/Nova"))
    args = parser.parse_args()
    head = subprocess.run(["git", "-C", args.nova, "describe", "--tags", "--always"], capture_output=True, text=True,
                          check=True).stdout.strip()
    dirty = subprocess.run(["git", "-C", args.nova, "status", "--porcelain", "docs"], capture_output=True, text=True,
                           check=True).stdout.strip()
    if dirty:
        sys.exit(f"gen_catalog: {args.nova}/docs has uncommitted changes")
    found = entries(args.nova)
    arms = "\n".join(f"    {int(code[1:])} => {literal(meaning)}," for code, meaning in sorted(found.items()))
    source = f"""// Each diagnostic code's meaning, as the reference's DiagnosticCatalog finds it in its embedded documents (the JSON
// "summary", tooling.md §5.1). GENERATED by tools/gen_catalog.py from Nova {head}: rerun it, do not edit.

/// The meaning of code N`number`, or "" for a code no document lists.
fn summaryOf(number: u32) -> StringView => match (number) {{
{arms}
    _ => "",
}};
"""
    path = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "src", "diagnostics", "catalog.nova"))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    novac = os.environ.get("NOVAC", os.path.expanduser("~/.nova/0.5.0/bin/novac"))
    subprocess.run([novac, "fmt", path], check=True)
    print(f"gen_catalog: wrote {path} ({len(found)} codes from Nova {head})")


if __name__ == "__main__":
    main()
